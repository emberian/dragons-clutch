//! The Hoard/Position seam plane: `Intent::Split`, and the shared account list,
//! validation order, kernel step, and write-back that
//! [`super::merge_materialize`] reuses for `Merge`, `Materialize`, and
//! `Dematerialize`.
//!
//! This module contains no economic logic.  Every transition is
//! [`clutch_kernel::MarketState`]; byte ownership is [`clutch_solana_layout`]
//! and the reference-only codecs of [`clutch_solana_reference`]; metadata
//! authentication and the CLO-DELTA-V1 primitives are [`crate::accounts`].
//! What lives here is the account list, the order of the checks, the program
//! addresses each account must be, and the write-back.
//!
//! ## The seam plane is one plane
//!
//! `Split`, `Merge`, `Materialize`, and `Dematerialize` are the four requests
//! the offline reference adapter routes through one `TransitionMetadata` /
//! `StateBytes` / `ExpectedBindings` triple, so they take one account list
//! here too.  Two modules own them (the ownership table in
//! `docs/implementation/SBF_BRINGUP.md` splits by family), but a second copy of
//! the account list would be a second place for the seam's writable set to
//! drift, so the list, the checks, and the write-back live here and
//! `merge_materialize` calls [`seam`].
//!
//! ## CLO-DELTA-V1 is now carried, not deferred
//!
//! The single-instruction bring-up program carried the retired closed
//! single-position equality `internal + external == total_supply` and took nine
//! accounts.  It now takes **ten**: the market-wide supply ledger, appended
//! after the replay account exactly as `ExpectedBindings::supply` is the last
//! state binding of the reference adapter.  The equality is replaced by the
//! three checked obligations of `docs/implementation/MULTI_POSITION_CLOSURE.md`
//! through [`crate::accounts`]:
//!
//! | obligation | where |
//! | --- | --- |
//! | C1 two-term closure against the kernel aggregate | [`accounts::require_two_term_closure`], pre-state and post-state |
//! | C2 representation bound on the presented triple | [`accounts::require_representation_bound`], pre-state and post-state |
//! | C3 ledger moved by exactly the position delta | [`accounts::apply_ledger_delta`], once per ledger term |
//!
//! A market holding a second position is therefore representable here, which is
//! the whole point of the change: the retired equality refused every such
//! market.
//!
//! ## Consequence for the emitted SVM fixtures
//!
//! `harness/` is frozen this wave and still emits a nine-account `Split`
//! transaction, so the transactions under `tx/` no longer match this
//! instruction's account count and the SVM leg of the differential must be
//! regenerated by the harness lane before it means anything again.  Its *host*
//! leg — the fixture build and the offline reference adapter run inside
//! `build_fixture` — is untouched and still passes.  The host differential in
//! this module is what covers the transitions in the meantime; the SVM-side
//! differential for the seam plane is a named follow-up wave.
//!
//! ## What the host differential does and does not cover
//!
//! [`seam`] takes its program addresses as an already-derived [`Bindings`]
//! value rather than deriving them inline, because program-address derivation
//! is a runtime syscall and [`crate::seeds::find`] is deliberately not compiled
//! for the host.  On-chain, [`process`] supplies [`derive_bindings`]; in the
//! host differential the test supplies the same trusted bindings the offline
//! reference adapter itself takes as `ExpectedBindings`.  So the differential
//! covers request decoding, metadata authentication, every linkage and closure
//! check, the kernel step, and the write-back — everything the reference
//! adapter models — and covers exactly one thing less than the SVM leg: that
//! the derived address is the canonical one.  That gap is the derivation, and
//! it is the reference adapter's own gap too.

