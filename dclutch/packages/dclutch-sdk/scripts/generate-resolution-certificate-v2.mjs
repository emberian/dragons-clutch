import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const source = readFileSync(new URL('crates/dclutch-resolution-codec/src/generated_v2.rs', root), 'utf8');
const outputUrl = new URL('../lib/generated/resolutionCertificateV2.ts', import.meta.url);

function scalar(name) {
  const match = source.match(new RegExp(`pub(?:\\(crate\\))? const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

function fixedBytes(name) {
  const match = source.match(new RegExp(`const ${name}: \\[u8; ([0-9]+)\\] = \\[([\\s\\S]*?)\\n\\];`));
  if (!match) throw new Error(`missing Rust byte array ${name}`);
  const bytes = [...match[2].matchAll(/0x([0-9a-f]{2})/g)].map((entry) => Number.parseInt(entry[1], 16));
  if (bytes.length !== Number(match[1])) throw new Error(`${name} has ${bytes.length} bytes, expected ${match[1]}`);
  return bytes;
}

function matrix(name) {
  const match = source.match(new RegExp(`const ${name}: \\[\\[u8; ([0-9]+)\\]; ([0-9]+)\\] = \\[([\\s\\S]*?)\\n\\];`));
  if (!match) throw new Error(`missing Rust byte matrix ${name}`);
  const width = Number(match[1]); const count = Number(match[2]);
  const bytes = [...match[3].matchAll(/0x([0-9a-f]{2})/g)].map((entry) => Number.parseInt(entry[1], 16));
  if (bytes.length !== width * count) throw new Error(`${name} has ${bytes.length} bytes, expected ${width * count}`);
  return Array.from({ length: count }, (_, index) => bytes.slice(index * width, (index + 1) * width));
}

function hex(bytes) { return bytes.map((byte) => byte.toString(16).padStart(2, '0')).join(''); }
function ascii(bytes) {
  if (bytes.some((byte) => byte < 0x20 || byte > 0x7e)) throw new Error('certificate magic is not printable ASCII');
  return String.fromCharCode(...bytes);
}

