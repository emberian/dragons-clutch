/**
 * `RationalReplayV2`'s byte coordinates and its PDA seed domain.
 *
 * Every Rational Open transaction reads this account before it is built: it is
 * the per-descriptor, per-actor optimistic cursor the Claims adapter advances
 * once, and the client both DECODES it to learn the current revision and
 * PREDICTS the poststate revision it expects to observe afterwards. A client
 * that reads it at the wrong coordinates does not fail loudly -- it signs a
 * transaction against a revision that was never there.
 *
 * `lib/rationalOpenChainV4.ts` stated the whole record itself: the magic, the
 * version, the 88-byte width, the reserved run and four field offsets, plus the
 * seed domain used to derive the account. This module is the same coordinates
 * read from the crate that owns them.
 *
 * AUTHORITY: hand-written Rust, NOT Lean. `RationalReplayV2` has no Lean schema
 * in `formal/`; `crates/dclutch-claims` declares
 * the layout in `src/replay.rs` and the seed in `src/lib.rs`, and is its only
 * owner. The magic offset is a literal at the decode site rather than a
 * declared constant, so it is scraped from `RationalReplayV2::decode` -- a
 * header convention that moves takes this generator red rather than leaving the
 * client reading the old one.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const crate = new URL('crates/dclutch-claims/src/rational/', root);
const layout = readFileSync(new URL('replay.rs', crate), 'utf8');
const contract = readFileSync(new URL('mod.rs', crate), 'utf8');
const outputUrl = new URL('../lib/generated/rationalReplayV2.ts', import.meta.url);

function scalar(name) {
  const match = layout.match(new RegExp(`(?:pub(?:\\(crate\\))? )?const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

/** A `*b"…"` literal magic, with its declared width proved against the text. */
function asciiMagic(name) {
  const match = layout.match(new RegExp(`const ${name}: \\[u8; ([0-9]+)\\] = \\*b"([\\x20-\\x7e]*)";`));
  if (!match) throw new Error(`missing Rust ASCII magic ${name}`);
  if (match[2].length !== Number(match[1])) throw new Error(`${name} is ${match[2].length} bytes, declared ${match[1]}`);
  return { text: match[2], bytes: [...match[2]].map((character) => character.charCodeAt(0)) };
}

function byteString(text, name) {
  const match = text.match(new RegExp(`const ${name}: &\\[u8\\] = b"([\\x20-\\x7e]*)";`));
  if (!match) throw new Error(`missing Rust byte string ${name}`);
  return match[1];
}

function list(bytes) { return `Uint8Array.from([${bytes.map((byte) => `0x${byte.toString(16).padStart(2, '0')}`).join(', ')}])`; }

/**
 * Every offset the contract declares for this record, in declaration order.
 *
 * Scraped rather than listed, so a coordinate added to the record arrives here
 * by regeneration instead of by somebody remembering a name, and so this
 * script cannot emit a SUBSET of the layout.
 */
const decode = layout.match(/pub fn decode\(bytes: &\[u8\]\)[\s\S]*?\n {4}\}/);
if (!decode) throw new Error('missing RationalReplayV2::decode');
const magicOffset = decode[0].match(/array_at::<8>\(bytes, ([0-9]+)\)\? != RATIONAL_REPLAY_MAGIC_V2/);
if (!magicOffset) throw new Error('RationalReplayV2::decode no longer reads its magic where this scrape expects it');
const reservedBytes = decode[0].match(/require_zero\(bytes, RESERVED_OFFSET, ([0-9]+)\)/);
if (!reservedBytes) throw new Error('RationalReplayV2::decode no longer pins a fixed reserved run');

const offsetNames = [...layout.matchAll(/^const ([A-Z0-9_]*_OFFSET): usize = [0-9_]+;/gm)].map((match) => match[1]);
if (offsetNames.length < 5) throw new Error(`only ${offsetNames.length} replay offsets found; the scrape is wrong`);

const magic = asciiMagic('RATIONAL_REPLAY_MAGIC_V2');
const seed = byteString(contract, 'RATIONAL_REPLAY_SEED_V2');
const lines = [
  '// @generated by scripts/generate-rational-replay-v2.mjs; do not edit.',
  '// Source: crates/dclutch-claims/src/rational/replay.rs (layout)',
  '// and src/rational/mod.rs (seed domain).',
  '//',
  '// AUTHORITY IS HAND-WRITTEN RUST, NOT LEAN. RationalReplayV2 has no Lean schema;',
  '// the contract crate above declares this record and is its only owner.',
  '',
  `export const RATIONAL_REPLAY_MAGIC_V2 = ${list(magic.bytes)};`,
  `export const RATIONAL_REPLAY_MAGIC_OFFSET = ${magicOffset[1]} as const;`,
  `export const RATIONAL_REPLAY_MAGIC_BYTES = ${magic.bytes.length} as const;`,
  `export const RATIONAL_REPLAY_BYTES_V2 = ${scalar('RATIONAL_REPLAY_BYTES_V2')} as const;`,
  `export const RATIONAL_REPLAY_VERSION_V2 = ${scalar('RATIONAL_REPLAY_VERSION_V2')} as const;`,
  `export const RATIONAL_REPLAY_RESERVED_BYTES = ${reservedBytes[1]} as const;`,
  '',
  ...offsetNames.map((name) => `export const RATIONAL_REPLAY_${name} = ${scalar(name)} as const;`),
  '',
  '/** Claims PDA seed domain: this seed, the descriptor identity, then the actor. */',
  `export const RATIONAL_REPLAY_SEED_V2 = '${seed}' as const;`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== lines) {
    process.stderr.write('lib/generated/rationalReplayV2.ts is stale; run npm run abi:rational-replay-v2\n');
    process.exit(1);
  }
  process.stdout.write('lib/generated/rationalReplayV2.ts matches its Rust source\n');
} else {
  writeFileSync(outputUrl, lines);
  process.stdout.write('wrote lib/generated/rationalReplayV2.ts\n');
}
