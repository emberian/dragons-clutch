const outputUrl = new URL('../lib/generated/directParticipantV1.ts', import.meta.url);

function scalar(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub )?const ${name}: [^=]+ = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${source}.${name}`);
  return Number(match[1].replaceAll('_', ''));
}

function magic(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub )?const ${name}: \\[u8; 8\\] = \\*b"([^"]+)";`));
  if (!match) throw new Error(`missing Rust magic ${source}.${name}`);
  return match[1];
}

function byteString(source, name) {
  const forward = sources[source].match(new RegExp(`(?:pub )?const ${name}: &\\[u8\\] =\\s*crate::liability_basis_state_v2::([A-Z0-9_]+);`));
  if (forward) return byteString('liabilityState', forward[1]);
  const match = sources[source].match(new RegExp(`(?:pub )?const ${name}: &\\[u8\\] =\\s*b"([^"]+)";`));
  if (!match) throw new Error(`missing Rust byte string ${source}.${name}`);
  return match[1];
}

function text(source, name) {
  const match = sources[source].match(new RegExp(`pub const ${name}: &str = "([^"]+)";`));
  if (!match) throw new Error(`missing Rust text ${source}.${name}`);
  return match[1];
}

function discriminant(source, enumeration, variant) {
  const body = sources[source].match(new RegExp(`(?:pub )?enum ${enumeration} \\{([\\s\\S]*?)\\n\\}`));
  const match = body?.[1].match(new RegExp(`\\n\\s*${variant} = ([0-9_]+),`));
  if (!match) throw new Error(`missing Rust ${enumeration}::${variant} discriminant`);
  return Number(match[1].replaceAll('_', ''));
}

