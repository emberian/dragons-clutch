/**
 * `RepresentationDescriptorV3`'s byte coordinates, for the clients that read one.
 *
 * The immutable descriptor is the record every Rational route joins against:
 * the graph it names, the Market it belongs to, the receipt Mint and token
 * program it fixes, its outcome width, its denominator, and the sparse
 * coefficient support that decides which physical coordinates exist at all.
 * `lib/rationalRetireReceiptV4.ts` decoded it through its own magic, its own
 * 256-byte header width, two reserved runs and seven identity offsets written
 * as a literal array -- and it also carried a hand-copied 32-byte schema
 * release id used to derive the descriptor's finalized record address.
 *
 * AUTHORITY: LEAN. Unlike the graph beside it, this record has a schema:
 * `formal/dclutch-semantics/EmitRationalRepresentationV2DescriptorRust.lean`
 * emits `crates/dclutch-rational-representation-v2-kernel/src/generated_descriptor.rs`,
 * and that emitted Rust is what this script reads. The two reserved-run widths
 * are pinned at the kernel decode site rather than declared, so they are
 * scraped from `RepresentationDescriptorV2::decode`; the schema release id and
 * its preimage are declared in the kernel crate root.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const crate = new URL('crates/dclutch-rational-representation-v2-kernel/src/', root);
const emitted = readFileSync(new URL('generated_descriptor.rs', crate), 'utf8');
const kernel = readFileSync(new URL('lib.rs', crate), 'utf8');
const outputUrl = new URL('../lib/generated/rationalRepresentationDescriptorV3.ts', import.meta.url);

/**
 * The Lean provenance line, read from the emitted Rust rather than asserted.
 *
 * If the descriptor ever stops being Lean-emitted this generator goes red
 * instead of quietly continuing to call itself Lean-backed.
 */
const provenance = emitted.match(/^\/\/ @generated by (formal\/[^\s;]+); do not edit\./m);
if (!provenance) throw new Error('generated_descriptor.rs no longer declares a Lean emitter; this module claims Lean authority it cannot show');

function scalar(text, name) {
  const match = text.match(new RegExp(`(?:pub(?:\\(crate\\))? )?const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

function fixedBytes(text, name) {
  const match = text.match(new RegExp(`const ${name}: \\[u8; ([0-9]+)\\] = \\[([\\s\\S]*?)\\];`));
  if (!match) throw new Error(`missing Rust byte array ${name}`);
  const bytes = [...match[2].matchAll(/0x([0-9a-f]{2})/g)].map((entry) => Number.parseInt(entry[1], 16));
  if (bytes.length !== Number(match[1])) throw new Error(`${name} has ${bytes.length} bytes, expected ${match[1]}`);
  return bytes;
}

function byteString(text, name) {
  const match = text.match(new RegExp(`const ${name}: &\\[u8\\] =\\s*b"([\\x20-\\x7e]*)";`));
  if (!match) throw new Error(`missing Rust byte string ${name}`);
  return match[1];
}

function list(bytes) { return `Uint8Array.from([${bytes.map((byte) => `0x${byte.toString(16).padStart(2, '0')}`).join(', ')}])`; }

/** One reserved run pinned at the kernel decode site rather than declared. */
const decode = kernel.match(/if array_at::<8>\(input, DESCRIPTOR_MAGIC_OFFSET\)[\s\S]*?validate_descriptor_admission/);
if (!decode) throw new Error('missing RepresentationDescriptorV2::decode header validation');
function reservedRun(name) {
  const match = decode[0].match(new RegExp(`require_zero\\(input, ${name}, ([0-9]+)\\)`));
  if (!match) throw new Error(`RepresentationDescriptorV2::decode no longer pins a fixed run at ${name}`);
  return match[1];
}

/**
 * Every offset the Lean-emitted Rust declares, in the order it declares them.
 *
 * Scraped rather than listed, so a coordinate added to the Lean schema arrives
 * here by regeneration instead of by somebody remembering to add a name -- and
 * so this script cannot silently emit a SUBSET of the record's layout.
 */
const offsetNames = [...emitted.matchAll(/^pub const (DESCRIPTOR_[A-Z0-9_]*_OFFSET): usize = [0-9_]+;/gm)].map((match) => match[1]);
if (offsetNames.length < 12) throw new Error(`only ${offsetNames.length} descriptor offsets found; the scrape is wrong`);

const magic = fixedBytes(emitted, 'DESCRIPTOR_MAGIC_V3');
const lines = [
  '// @generated by scripts/generate-rational-representation-descriptor-v3.mjs; do not edit.',
  `// Source: crates/dclutch-rational-representation-v2-kernel/src/generated_descriptor.rs,`,
  `// itself @generated by ${provenance[1]}.`,
  '// The two reserved-run widths and the schema release id come from that crate root.',
  '',
  `export const DESCRIPTOR_MAGIC_V3 = ${list(magic)};`,
  `export const DESCRIPTOR_MAGIC_BYTES = ${magic.length} as const;`,
  `export const DESCRIPTOR_SCHEMA_VERSION_V3 = ${scalar(emitted, 'DESCRIPTOR_SCHEMA_VERSION_V3')} as const;`,
  `export const DESCRIPTOR_HEADER_BYTES = ${scalar(emitted, 'DESCRIPTOR_HEADER_BYTES')} as const;`,
  `export const DESCRIPTOR_COEFFICIENT_BYTES = ${scalar(emitted, 'DESCRIPTOR_COEFFICIENT_BYTES')} as const;`,
  `export const DESCRIPTOR_RESERVED_HEADER_BYTES = ${reservedRun('DESCRIPTOR_RESERVED_HEADER_OFFSET')} as const;`,
  `export const DESCRIPTOR_RESERVED_BYTES = ${reservedRun('DESCRIPTOR_RESERVED_OFFSET')} as const;`,
  '',
  ...offsetNames.map((name) => `export const ${name} = ${scalar(emitted, name)} as const;`),
  '',
  '/** The finalized-record schema one descriptor is published under. */',
  `export const REPRESENTATION_DESCRIPTOR_SCHEMA_RELEASE_PREIMAGE_V3 = '${byteString(kernel, 'REPRESENTATION_DESCRIPTOR_SCHEMA_RELEASE_PREIMAGE_V3')}' as const;`,
  `export const REPRESENTATION_DESCRIPTOR_SCHEMA_RELEASE_ID_V3 = ${list(fixedBytes(kernel, 'REPRESENTATION_DESCRIPTOR_SCHEMA_RELEASE_ID_V3'))};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== lines) {
    process.stderr.write('lib/generated/rationalRepresentationDescriptorV3.ts is stale; run npm run abi:rational-descriptor-v3\n');
    process.exit(1);
  }
  process.stdout.write('lib/generated/rationalRepresentationDescriptorV3.ts matches its Lean-emitted Rust source\n');
} else {
  writeFileSync(outputUrl, lines);
  process.stdout.write('wrote lib/generated/rationalRepresentationDescriptorV3.ts\n');
}
