import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const generated = readFileSync(new URL('crates/dclutch-source-contract/src/generated_principal_capacity_v1.rs', root), 'utf8');
const outputUrl = new URL('../lib/generated/principalCapacityV1.ts', import.meta.url);

function scalar(name) {
  const match = generated.match(new RegExp(`pub const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

/**
 * Lift the Lean-emitted admission corpus.
 *
 * `PRINCIPAL_ADMISSION_CASES_V1` is emitted by
 * `formal/dclutch-semantics/EmitSourcePrincipalCapacityV1Rust.lean` from the
 * same model that proves `admit_sound` and `admit_complete`. Carrying it across
 * verbatim means the browser's kappa arithmetic is graded against the machine
 * checked statement rather than against a second reading of the Rust.
 */
function admissionCases() {
  const block = generated.match(/pub const PRINCIPAL_ADMISSION_CASES_V1: \[PrincipalAdmissionCaseV1; ([0-9]+)\] = \[([\s\S]*?)\n\];/);
  if (!block) throw new Error('missing Rust PRINCIPAL_ADMISSION_CASES_V1 corpus');
  const declared = Number(block[1]);
  const cases = [...block[2].matchAll(/PrincipalAdmissionCaseV1 \{\s*numerator: ([0-9_]+),\s*denominator: ([0-9_]+),\s*floor_atoms: ([0-9_]+),\s*principal_atoms: ([0-9_]+),\s*admitted: (true|false),\s*\}/g)]
    .map((entry) => ({
      numerator: entry[1].replaceAll('_', ''),
      denominator: entry[2].replaceAll('_', ''),
      floorAtoms: entry[3].replaceAll('_', ''),
      principalAtoms: entry[4].replaceAll('_', ''),
      admitted: entry[5] === 'true',
    }));
  if (cases.length !== declared) throw new Error(`parsed ${cases.length} admission cases, not the ${declared} the array declares`);
  return cases;
}

const lines = [];
lines.push('// @generated by scripts/generate-principal-capacity.mjs; do not edit.');
lines.push('// Regenerate with: npm run abi:principal-capacity');
lines.push('//');
lines.push('// Source: crates/dclutch-source-contract/src/generated_principal_capacity_v1.rs,');
lines.push('// itself emitted by formal/dclutch-semantics/EmitSourcePrincipalCapacityV1Rust.lean.');
lines.push('');
lines.push('/** The conservative default for a chain-state Source: kappa = 1/4. */');
lines.push(`export const CHAIN_STATE_DEFAULT_KAPPA_NUMERATOR_V1 = ${scalar('CHAIN_STATE_DEFAULT_KAPPA_NUMERATOR_V1')} as const;`);
lines.push(`export const CHAIN_STATE_DEFAULT_KAPPA_DENOMINATOR_V1 = ${scalar('CHAIN_STATE_DEFAULT_KAPPA_DENOMINATOR_V1')} as const;`);
lines.push('');
lines.push('/** The venue floor the default kappa is scaled against, in lamports. */');
lines.push(`export const BONDING_CURVE_GRADUATION_FLOOR_LAMPORTS_V1 = ${scalar('BONDING_CURVE_GRADUATION_FLOOR_LAMPORTS_V1')}n as const;`);
lines.push('');
lines.push('/** `ManipulationFloorV1` layout, for a decoder that reads a real floor record. */');
for (const name of [
  'MANIPULATION_FLOOR_V1_BYTES',
  'MANIPULATION_FLOOR_V1_SCHEMA_VERSION',
  'MANIPULATION_FLOOR_V1_MAGIC_OFFSET',
  'MANIPULATION_FLOOR_V1_VERSION_OFFSET',
  'MANIPULATION_FLOOR_V1_BASIS_OFFSET',
  'MANIPULATION_FLOOR_V1_RESERVED_OFFSET',
  'MANIPULATION_FLOOR_V1_RESERVED_BYTES',
  'MANIPULATION_FLOOR_V1_SOURCE_SPEC_OFFSET',
  'MANIPULATION_FLOOR_V1_ADAPTER_CONFIG_OFFSET',
  'MANIPULATION_FLOOR_V1_COLLATERAL_UNIT_OFFSET',
  'MANIPULATION_FLOOR_V1_DERIVATION_RELEASE_OFFSET',
  'MANIPULATION_FLOOR_V1_FLOOR_ATOMS_OFFSET',
  'MANIPULATION_FLOOR_V1_TAIL_RESERVED_OFFSET',
  'MANIPULATION_FLOOR_V1_TAIL_RESERVED_BYTES',
  'MANIPULATION_FLOOR_V1_CURVE_DERIVED_TAG',
  'MANIPULATION_FLOOR_V1_OBSERVED_DEPTH_TAG',
  'SOURCE_CAPACITY_PRINCIPAL_NUMERATOR_OFFSET_V1',
  'SOURCE_CAPACITY_PRINCIPAL_DENOMINATOR_OFFSET_V1',
]) {
  lines.push(`export const ${name} = ${scalar(name)} as const;`);
}
lines.push('');
lines.push('/**');
lines.push(' * The Lean-emitted founding-admission corpus, carried across verbatim.');
lines.push(' *');
lines.push(' * `lib/founding/principalCapacity.test.ts` runs the browser predicate over');
lines.push(' * every row and requires the same verdict, which makes the port differential');
lines.push(' * against the model rather than against a second reading of the Rust.');
lines.push(' */');
lines.push('export const PRINCIPAL_ADMISSION_CASES_V1 = Object.freeze([');
for (const entry of admissionCases()) {
  lines.push(`  Object.freeze({ numerator: ${entry.numerator}, denominator: ${entry.denominator}, floorAtoms: ${entry.floorAtoms}n, principalAtoms: ${entry.principalAtoms}n, admitted: ${entry.admitted} }),`);
}
lines.push('] as const);');
lines.push('');

const emitted = lines.join('\n');
if (process.argv.includes('--check')) {
  const current = readFileSync(outputUrl, 'utf8');
  if (current !== emitted) {
    process.stderr.write('lib/generated/principalCapacityV1.ts is stale; run npm run abi:principal-capacity\n');
    process.exit(1);
  }
  process.stdout.write('lib/generated/principalCapacityV1.ts matches its Rust source\n');
} else {
  writeFileSync(outputUrl, emitted);
  process.stdout.write('wrote lib/generated/principalCapacityV1.ts\n');
}
