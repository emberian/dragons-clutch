import { readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../../../', import.meta.url);
const sourceUrl = new URL('crates/dclutch-market/src/retirement_checkpoint_v1.rs', root);
const source = readFileSync(sourceUrl, 'utf8');
const outputUrl = new URL('../lib/generated/aggregateRetirementV1.ts', import.meta.url);

function scalar(name) {
  const match = source.match(new RegExp(`(?:pub )?const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

function ascii(name) {
  const match = source.match(new RegExp(`pub const ${name}: \\[u8; 8\\] = \\*b"([ -~]{8})";`));
  if (!match) throw new Error(`missing Rust ASCII magic ${name}`);
  return match[1];
}

function phase(name) {
  const match = source.match(new RegExp(`\\b${name} = ([0-9_]+),`));
  if (!match) throw new Error(`missing Rust retirement phase ${name}`);
  return match[1].replaceAll('_', '');
}

function capture(pattern, field) {
  const match = source.match(pattern);
  if (!match) throw new Error(`missing Rust checkpoint ${field}`);
  return match[1].replaceAll('_', '');
}

// The four header coordinates are written directly at the Rust encode/decode
// sites. Extracting them keeps this generated module authority-backed even
// though the semantic owner does not publish separate constants for them.
const magicOffset = capture(/put\(&mut output, ([0-9_]+), &AGGREGATE_RETIREMENT_CHECKPOINT_MAGIC_V1\);/, 'magic offset');
const versionOffset = capture(/put_u16\(\s*&mut output,\s*([0-9_]+),\s*AGGREGATE_RETIREMENT_CHECKPOINT_VERSION_V1\s*\);/, 'version offset');
const phaseOffset = capture(/output\[([0-9_]+)\] = self\.phase as u8;/, 'phase offset');
const reservedOffset = capture(/require_zero\(input, ([0-9_]+), 5\)\?;/, 'reserved offset');
const reservedBytes = capture(/require_zero\(input, [0-9_]+, ([0-9_]+)\)\?;/, 'reserved width');

const scalarNames = [
  'AGGREGATE_RETIREMENT_CHECKPOINT_BYTES_V1',
  'AGGREGATE_RETIREMENT_SUFFIX_REQUEST_BYTES_V1',
  'AGGREGATE_RETIREMENT_CHECKPOINT_VERSION_V1',
  'CORE_PRESTATE_OFFSET',
  'BUNDLE_DIGEST_OFFSET',
  'CLAIMS_CONTEXT_OFFSET',
  'CLAIMS_RECEIPT_OFFSET',
  'VAULT_RECEIPT_OFFSET',
  'REPLAY_RECEIPT_OFFSET',
  'CLAIMS_REFUND_OFFSET',
  'CUSTODY_REFUND_OFFSET',
  'GENERATION_OFFSET',
  'CLAIMS_REVISION_OFFSET',
  'CUSTODY_REVISION_OFFSET',
  'PHASE_REVISION_OFFSET',
];

const lines = [
  '// @generated by scripts/generate-aggregate-retirement-v1.mjs; do not edit.',
  '// Source: crates/dclutch-market/src/retirement_checkpoint_v1.rs.',
  '',
  `export const AGGREGATE_RETIREMENT_CHECKPOINT_MAGIC_V1 = '${ascii('AGGREGATE_RETIREMENT_CHECKPOINT_MAGIC_V1')}' as const;`,
  `export const AGGREGATE_RETIREMENT_CLOSE_VAULT_MAGIC_V1 = '${ascii('AGGREGATE_RETIREMENT_CLOSE_VAULT_MAGIC_V1')}' as const;`,
  `export const AGGREGATE_RETIREMENT_CLOSE_REPLAY_MAGIC_V1 = '${ascii('AGGREGATE_RETIREMENT_CLOSE_REPLAY_MAGIC_V1')}' as const;`,
  `export const AGGREGATE_RETIREMENT_FINISH_MAGIC_V1 = '${ascii('AGGREGATE_RETIREMENT_FINISH_MAGIC_V1')}' as const;`,
  ...scalarNames.map((name) => `export const ${name} = ${scalar(name)} as const;`),
  `export const AGGREGATE_RETIREMENT_MAGIC_OFFSET_V1 = ${magicOffset} as const;`,
  `export const AGGREGATE_RETIREMENT_VERSION_OFFSET_V1 = ${versionOffset} as const;`,
  `export const AGGREGATE_RETIREMENT_PHASE_OFFSET_V1 = ${phaseOffset} as const;`,
  `export const AGGREGATE_RETIREMENT_RESERVED_OFFSET_V1 = ${reservedOffset} as const;`,
  `export const AGGREGATE_RETIREMENT_RESERVED_BYTES_V1 = ${reservedBytes} as const;`,
  `export const AGGREGATE_RETIREMENT_PHASE_CLAIMS_CLOSED_V1 = ${phase('ClaimsClosed')} as const;`,
  `export const AGGREGATE_RETIREMENT_PHASE_HOARD_VAULT_CLOSED_V1 = ${phase('HoardVaultClosed')} as const;`,
  `export const AGGREGATE_RETIREMENT_PHASE_CUSTODY_REPLAY_CLOSED_V1 = ${phase('CustodyReplayClosed')} as const;`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== lines) {
    process.stderr.write('lib/generated/aggregateRetirementV1.ts is stale; run npm run abi:aggregate-retirement\n');
    process.exit(1);
  }
  process.stdout.write('lib/generated/aggregateRetirementV1.ts matches its Rust source\n');
} else {
  const outputPath = fileURLToPath(outputUrl);
  const temporary = join(dirname(outputPath), `.aggregate-retirement-v1.${process.pid}.tmp`);
  try {
    writeFileSync(temporary, lines, { flag: 'wx' });
    const candidate = readFileSync(temporary, 'utf8');
    if (!candidate.startsWith('// @generated by scripts/generate-aggregate-retirement-v1.mjs;')
        || !candidate.includes('AGGREGATE_RETIREMENT_CHECKPOINT_BYTES_V1 = 256 as const;')) {
      throw new Error('generated aggregate-retirement module failed its header or width validation');
    }
    renameSync(temporary, outputPath);
  } finally {
    rmSync(temporary, { force: true });
  }
  process.stdout.write('wrote lib/generated/aggregateRetirementV1.ts\n');
}
