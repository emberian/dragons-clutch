#!/bin/sh
set -eu

# The lifecycle rent V2 ABI: six records, thirty coordinates, three magics, two
# seed domains and the action alphabet. All of it was written by hand in
# `lifecycle_v2.rs` until the emission existed, and the browser reached the
# credit magic's coordinate by running a regular expression over the ENCODER'S
# CALL because there was no constant to read.

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"

candidate=$(mktemp "${TMPDIR:-/tmp}/dclutch-generated.XXXXXX")
trap 'rm -f "$candidate"' EXIT HUP INT TERM

# Assert the provenance header and that the emitter produced a whole file
# rather than a truncated one, then normalize with the repository's pinned
# rustfmt and byte-compare. Formatting is normalized rather than asserted
# because the committed bytes are rustfmt output, not raw emitter output.
verify() {
  emitter=$1
  target=$2
  minimum_lines=$3
  test "$(sed -n '1p' "$candidate")" = "// @generated by formal/dclutch-semantics/$emitter; do not edit."
  test "$(wc -l <"$candidate" | tr -d ' ')" -ge "$minimum_lines"
  rustfmt --edition 2024 "$candidate"
  cmp "$candidate" "$crate_dir/src/rent/$target"
}

(
  cd "$formal_dir"
  lake build DClutchSemantics.LifecycleRentV2Abi >/dev/null
  lake env lean --run EmitLifecycleRentV2Rust.lean >"$candidate"
)
grep -q '^pub const LIFECYCLE_RENT_CREDIT_BYTES_V2: usize = 128;$' "$candidate"
grep -q '^pub const CLOSE_LIFECYCLE_RENT_CREDIT_BYTES_V2: usize = 528;$' "$candidate"
grep -q '^pub const LIFECYCLE_RENT_ACTION_CREATE_V2: u8 = 1;$' "$candidate"
verify EmitLifecycleRentV2Rust.lean generated_lifecycle_v2.rs 60
