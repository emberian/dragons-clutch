#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/capability_manifest/.generated-abi.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.CapabilityManifestV1Abi
  lake env lean --run EmitCapabilityManifestV1AbiRust.lean > "$generated"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitCapabilityManifestV1AbiRust.lean; do not edit.'
# Every width below is committed to by live Market capability content
# identities; a silent change here would name different Markets.
grep -q '^pub const CAPABILITY_MANIFEST_HEADER_BYTES_V1: usize = 16;$' "$generated"
grep -q '^pub const CAPABILITY_ENTRY_BYTES_V1: usize = 528;$' "$generated"
grep -q '^pub const CAPABILITY_MANIFEST_MAX_BYTES_V1: usize = 8464;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_QUOTE_BYTES_V1: usize = 304;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_STATE_BYTES_V1: usize = 320;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_HEADER_BYTES_V2: usize = 48;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_SLOT_BYTES_V2: usize = 72;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_AMOUNTS_BYTES_V1: usize = 128;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_BINDING_BYTES_V1: usize = 160;$' "$generated"
grep -q '^pub const MARKET_OPENING_READINESS_BYTES_V1: usize = 128;$' "$generated"
grep -q '^pub const CAPABILITY_ENTRY_QUOTE_OFFSET_V1: usize = 224;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_STATE_REMAINING_RENT_AMOUNT_OFFSET_V1: usize = 72;$' "$generated"
# The per-ROW machine's three wire tags, and the byte they are written at.
# They were `funding.rs`'s alone: an `#[repr(u8)]` enum with literal
# discriminants, which is the strongest form Rust offers and is still one
# author for a fact this module already owned the coordinate of. `Pending = 0`
# is pinned because a ledger account is created at width and read before
# anything is written, so the zero tag IS the intended initial state and a
# renumbering would silently reclassify every fresh slot.
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_SLOT_STATUS_OFFSET_V2: usize = 0;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_STATUS_PENDING_V2: u8 = 0;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_STATUS_ACTIVE_V2: u8 = 1;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_STATUS_CLOSED_V2: u8 = 2;$' "$generated"
grep -q '^pub const CAPABILITY_FUNDING_LEDGER_STATUS_LIMIT_V2: u8 = 3;$' "$generated"
rustfmt --edition 2024 "$generated"
cmp "$generated" "$crate_dir/src/capability_manifest/generated_abi.rs"
