#!/bin/sh
set -eu

# The Series V3 template and occurrence layouts. Both widths are persisted, and
# both were generated with nothing re-running the emitter.

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"

candidate=$(mktemp "${TMPDIR:-/tmp}/dclutch-generated.XXXXXX")
trap 'rm -f "$candidate"' EXIT HUP INT TERM

# Assert the provenance header, normalize with the repository's pinned rustfmt,
# then assert the emitter produced a whole file rather than a truncated one and
# byte-compare. Formatting is normalized rather than asserted because the
# committed bytes are rustfmt output, not raw emitter output; `rustfmt`
# resolves through rust-toolchain.toml from inside the tree.
#
# The width assertion runs AFTER rustfmt, and that ordering is the whole point:
# a floor is chosen by reading `wc -l` of the committed file, and the committed
# file is rustfmt output. Tested against the RAW emission the same number means
# something else -- the Expire block's floor of 60 was read off a 95-line
# committed file and tested against 57 raw lines, so that guard refused its own
# emission from the commit that introduced it and no gate ran it to say so.
#
# Each emission is spelled out rather than folded into a loop, because the
# emission census matches `lake env lean --run <Emitter>` literally: an emitter
# reached through a shell variable is an emitter the census cannot see, and a
# guard the census cannot see guards nothing as far as the ratchet is concerned.
verify() {
  emitter=$1
  target=$2
  minimum_lines=$3
  test "$(sed -n '1p' "$candidate")" = "// @generated by formal/dclutch-semantics/$emitter; do not edit."
  rustfmt --edition 2024 "$candidate"
  test "$(wc -l <"$candidate" | tr -d ' ')" -ge "$minimum_lines"
  cmp "$candidate" "$crate_dir/src/series/$target"
}

(
  cd "$formal_dir"
  lake build DClutchSemantics.SeriesOccurrenceV3Abi >/dev/null
  lake env lean --run EmitSeriesOccurrenceV3Rust.lean >"$candidate"
)
grep -q '^pub const SERIES_TEMPLATE_SCHEMA_V3: u16 = 3;$' "$candidate"
grep -q '^pub const SERIES_TEMPLATE_BYTES_V3: usize = 400;$' "$candidate"
grep -q '^pub const SERIES_OCCURRENCE_BYTES_V3: usize = 288;$' "$candidate"
verify EmitSeriesOccurrenceV3Rust.lean generated.rs 70

# The occurrence-ticket replay state's tag ABI. Its three wire tags were
# `replay.rs`'s alone and its phase coordinate had no name in any language:
# `encode` wrote `output[12]` and `decode` read `read_u8(bytes, 12)`, and the
# SDK generator recovered the offset by matching those two expressions and
# requiring them to agree -- against an encode line that belongs to
# `SeriesStateV3`, not to this record. The pins below are the width, the phase
# coordinate, the tag a zeroed account decodes as, and the two canonical-zero
# spans, because a tag that silently moved would let a client render a consumed
# ticket as retryable.
(
  cd "$formal_dir"
  lake build DClutchSemantics.SeriesTicketStateV3Abi >/dev/null
  lake env lean --run EmitSeriesTicketStateV3Rust.lean >"$candidate"
)
grep -q '^pub const SERIES_TICKET_STATE_BYTES_V3: usize = 64;$' "$candidate"
grep -q '^pub const SERIES_TICKET_STATE_PHASE_OFFSET_V3: usize = 12;$' "$candidate"
grep -q '^pub const SERIES_TICKET_PHASE_PREPARED_V3: u8 = 0;$' "$candidate"
grep -q '^pub const SERIES_TICKET_PHASE_CONSUMED_V3: u8 = 1;$' "$candidate"
grep -q '^pub const SERIES_TICKET_PHASE_EXPIRED_V3: u8 = 2;$' "$candidate"
grep -q '^pub const SERIES_TICKET_STATE_HEAD_RESERVED_OFFSET_V3: usize = 13;$' "$candidate"
grep -q '^pub const SERIES_TICKET_STATE_TAIL_RESERVED_OFFSET_V3: usize = 56;$' "$candidate"
verify EmitSeriesTicketStateV3Rust.lean generated_ticket_state_v3.rs 30

# The Series Expire V5 account frame. Its width had TWO authors on 2026-09-06
# and they disagreed -- the profile emitter said 82 and Trading's pre-Market
# authenticator said 81 -- and every commit between them compiled. The pins
# below are the count, the callee coordinate that is last and past every route
# window, and the alias-table width, because a frame two files spell is a frame
# nobody owns.
(
  cd "$formal_dir"
  lake build DClutchSemantics.SeriesExpireFrameV5Abi >/dev/null
  lake env lean --run EmitSeriesExpireFrameV5Rust.lean >"$candidate"
)
grep -q '^pub const SERIES_EXPIRE_FIXED_ACCOUNT_COUNT_V5: u16 = 82;$' "$candidate"
grep -q '^pub const SERIES_EXPIRE_CUSTODY_PROGRAM_COORDINATE_V5: u16 = 81;$' "$candidate"
grep -q '^pub const SERIES_EXPIRE_PRECOMMIT_CALLER_COORDINATE_V5: u16 = 80;$' "$candidate"
grep -q '^pub const SERIES_EXPIRE_FUTURE_MARKET_COORDINATE_V5: u16 = 7;$' "$candidate"
grep -q '^pub const SERIES_EXPIRE_ROUTE_STARTS_V5: \[u16; 5\] = \[6, 20, 34, 44, 55\];$' "$candidate"
grep -q '^pub const SERIES_EXPIRE_ROUTE_ALIASES_V5: \[(u16, u16); 37\]' "$candidate"
verify EmitSeriesExpireFrameV5Rust.lean generated_expire_frame_v5.rs 60

# The Series root tail. Its offsets were bare literals in replay.rs, twice each
# (encode and decode), and the SDK's state-machine generator had no root phase
# machine to read because nothing named the phase byte. The pins are the width,
# the phase coordinate, the two canonical-zero spans and the terminal tag.
(
  cd "$formal_dir"
  lake build DClutchSemantics.SeriesStateV3Abi >/dev/null
  lake env lean --run EmitSeriesStateV3Rust.lean >"$candidate"
)
grep -q '^pub const SERIES_STATE_BYTES_V3: usize = 64;$' "$candidate"
grep -q '^pub const SERIES_STATE_PHASE_OFFSET_V3: usize = 12;$' "$candidate"
grep -q '^pub const SERIES_STATE_HEAD_RESERVED_OFFSET_V3: usize = 14;$' "$candidate"
grep -q '^pub const SERIES_STATE_TAIL_RESERVED_OFFSET_V3: usize = 40;$' "$candidate"
grep -q '^pub const SERIES_PHASE_TERMINAL_V3: u8 = 1;$' "$candidate"
verify EmitSeriesStateV3Rust.lean generated_series_state_v3.rs 20
