#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/.generated-abi.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.RealmPositionAbi
  lake env lean --run EmitRealmPositionAbiRust.lean > "$generated"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitRealmPositionAbiRust.lean; do not edit.'
grep -q '^pub const REALM_BYTES_V1: usize = 112;$' "$generated"
grep -q '^pub const REALM_PDA_DOMAIN_V1: &\[u8\] = b"dclutch/realm/v1";$' "$generated"
# The seed domain outlived the record it was written for: the Direct
# controller's per-outcome Position family derives against it on every trade,
# while the compact native `PositionV1` was banished with the DCLTCAT1 stratum.
grep -q '^pub const POSITION_PDA_DOMAIN_V1: &\[u8\] = b"dclutch/position/v1";$' "$generated"
# And the record's coordinates are NOT emitted any more. A byte compare cannot
# catch a re-added constant that both sides agree on, so the absence is
# asserted rather than assumed.
! grep -q 'POSITION_MAGIC_V1' "$generated"
! grep -q 'POSITION_BASE_BYTES_V1' "$generated"
! grep -q 'MAX_POSITION_BYTES_V1' "$generated"
rustfmt --edition 2024 "$generated"
cmp "$generated" "$crate_dir/src/generated_abi.rs"
