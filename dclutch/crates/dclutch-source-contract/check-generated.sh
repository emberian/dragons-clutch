#!/bin/sh
set -eu

# Six Source emissions, every one a persisted layout or a decision corpus, and
# not one of them had a guard: material V2 and V3, the principal capacity
# floor, the recovery policy, the resolution state, and the scheduled median
# window specification.

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"

candidate=$(mktemp "${TMPDIR:-/tmp}/dclutch-generated.XXXXXX")
trap 'rm -f "$candidate"' EXIT HUP INT TERM

# Assert the provenance header and that the emitter produced a whole file
# rather than a truncated one, then normalize with the repository's pinned
# rustfmt and byte-compare. Formatting is normalized rather than asserted
# because the committed bytes are rustfmt output, not raw emitter output;
# `rustfmt` resolves through rust-toolchain.toml from inside the tree.
#
# Each emission is spelled out rather than folded into a loop, because the
# emission census matches `lake env lean --run <Emitter>` literally: an emitter
# reached through a shell variable is an emitter the census cannot see, and a
# guard the census cannot see guards nothing as far as the ratchet is concerned.
verify() {
  emitter=$1
  target=$2
  minimum_lines=$3
  test "$(sed -n '1p' "$candidate")" = "// @generated by formal/dclutch-semantics/$emitter; do not edit."
  test "$(wc -l <"$candidate" | tr -d ' ')" -ge "$minimum_lines"
  rustfmt --edition 2024 "$candidate"
  cmp "$candidate" "$crate_dir/src/$target"
}

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceMaterialV2Abi >/dev/null
  lake env lean --run EmitSourceMaterialV2AbiRust.lean >"$candidate"
)
grep -q '^pub const SOURCE_MATERIAL_V2_BYTES: usize = 208;$' "$candidate"
grep -q '^pub const SOURCE_MATERIAL_V2_SCHEMA_VERSION: u16 = 2;$' "$candidate"
verify EmitSourceMaterialV2AbiRust.lean generated_source_material_v2.rs 200

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceMaterialV3Abi >/dev/null
  lake env lean --run EmitSourceMaterialV3AbiRust.lean >"$candidate"
)
grep -q '^pub const SOURCE_MATERIAL_V3_BYTES: usize = 240;$' "$candidate"
grep -q '^pub const SOURCE_MATERIAL_V3_SCHEMA_VERSION: u16 = 3;$' "$candidate"
verify EmitSourceMaterialV3AbiRust.lean generated_source_material_v3.rs 280

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourcePrincipalCapacityV1 >/dev/null
  lake env lean --run EmitSourcePrincipalCapacityV1Rust.lean >"$candidate"
)
grep -q '^pub const MANIPULATION_FLOOR_V1_BYTES: usize = 160;$' "$candidate"
verify EmitSourcePrincipalCapacityV1Rust.lean generated_principal_capacity_v1.rs 420

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceRecoveryPolicyV2Abi >/dev/null
  lake env lean --run EmitSourceRecoveryPolicyV2AbiRust.lean >"$candidate"
)
grep -q '^pub const RECOVERY_ATTEMPT_BYTES_V2: usize = 112;$' "$candidate"
grep -q '^pub const RECOVERY_POLICY_BYTES_V2: usize = 496;$' "$candidate"
grep -q '^pub const RECOVERY_POLICY_MAX_ATTEMPTS_V2: usize = 4;$' "$candidate"
verify EmitSourceRecoveryPolicyV2AbiRust.lean generated_source_recovery_policy_v2.rs 440

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceResolutionStateV2Abi >/dev/null
  lake env lean --run EmitSourceResolutionStateV2AbiRust.lean >"$candidate"
)
grep -q '^pub const SOURCE_RESOLUTION_STATE_V2_BYTES: usize = 224;$' "$candidate"
grep -q '^pub const SOURCE_RESOLUTION_STATE_V2_SCHEMA_VERSION: u16 = 2;$' "$candidate"
verify EmitSourceResolutionStateV2AbiRust.lean generated_source_resolution_state_v2.rs 300

(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceScheduledMedianV1 >/dev/null
  lake env lean --run EmitSourceScheduledMedianV1Rust.lean >"$candidate"
)
grep -q '^pub const WINDOW_SPEC_CADENCE_TOLERANCE_OFFSET_V1: usize = 104;$' "$candidate"
verify EmitSourceScheduledMedianV1Rust.lean generated_scheduled_median_v1.rs 180

# The seventh: the whole WindowSpecV1 preimage. Its tail two coordinates stay
# with the scheduled median's emitter above -- one Lean author, one Rust
# definition of each constant -- so the pins below are the head's, and the width
# is the one the two old authors each stated separately.
(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceWindowSpecV1Abi >/dev/null
  lake env lean --run EmitSourceWindowSpecV1Rust.lean >"$candidate"
)
grep -q '^pub const WINDOW_SPEC_BYTES: usize = 112;$' "$candidate"
grep -q '^pub const WINDOW_SPEC_START_UNIX_SECONDS_OFFSET_V1: usize = 48;$' "$candidate"
grep -q '^pub const WINDOW_SPEC_END_UNIX_SECONDS_OFFSET_V1: usize = 56;$' "$candidate"
verify EmitSourceWindowSpecV1Rust.lean generated_window_spec_v1.rs 28

# The eighth: the whole StatisticSpecV1 preimage. Its sibling above has been
# Lean-owned since `SourceWindowSpecV1Abi.lean`; this one was not, and on
# 2026-09-03 `source_scale_exponent` -- the number that decides which cell a
# market pays -- landed at byte 12 of a layout nothing emitted. The pins below
# are the width, the two identities the shift relates, and the shift's own
# coordinate: a record that silently moved that field would re-mis-pay
# cohort-14 market B, so it is pinned here rather than only compared.
(
  cd "$formal_dir"
  lake build DClutchSemantics.SourceStatisticSpecV1Abi >/dev/null
  lake env lean --run EmitSourceStatisticSpecV1Rust.lean >"$candidate"
)
grep -q '^pub const STATISTIC_SPEC_BYTES: usize = 176;$' "$candidate"
grep -q '^pub const STATISTIC_SPEC_SOURCE_SCALE_EXPONENT_OFFSET_V1: usize = 12;$' "$candidate"
grep -q '^pub const STATISTIC_SPEC_SOURCE_SCALE_EXPONENT_BYTES_V1: usize = 4;$' "$candidate"
grep -q '^pub const STATISTIC_SPEC_SOURCE_UNIT_ID_OFFSET_V1: usize = 16;$' "$candidate"
grep -q '^pub const STATISTIC_SPEC_RESULT_UNIT_ID_OFFSET_V1: usize = 48;$' "$candidate"
verify EmitSourceStatisticSpecV1Rust.lean generated_statistic_spec_v1.rs 34
