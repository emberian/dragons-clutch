#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/.generated-capability-execution.XXXXXX")
infrastructure=$(mktemp "$crate_dir/src/.generated-protocol-infrastructure.XXXXXX")
trap 'rm -f "$generated" "$infrastructure"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.CapabilityExecutionAbi
  lake build DClutchSemantics.ProtocolInfrastructureProfileAbi
  lake env lean --run EmitCapabilityExecutionAbiRust.lean > "$generated"
  lake env lean --run EmitProtocolInfrastructureProfileAbiRust.lean > "$infrastructure"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitCapabilityExecutionAbiRust.lean; do not edit.'
grep -q '^pub const CAPABILITY_EXECUTION_SELECTION_BYTES_V1: usize = 144;$' "$generated"
rustfmt --edition 2024 "$generated"
cmp "$generated" "$crate_dir/src/generated_capability_execution.rs"

first_line=$(sed -n '1p' "$infrastructure")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitProtocolInfrastructureProfileAbiRust.lean; do not edit.'
grep -q '^pub const PROTOCOL_INFRASTRUCTURE_PROFILE_BYTES_V1: usize = 144;$' "$infrastructure"
grep -q '^pub const INITIALIZE_PROTOCOL_INFRASTRUCTURE_BYTES_V1: usize = 16;$' "$infrastructure"
rustfmt --edition 2024 "$infrastructure"
cmp "$infrastructure" "$crate_dir/src/generated_protocol_infrastructure.rs"
