#!/bin/sh
set -eu

# The Product V2 admission emission: three wire records and the 128-byte
# finalized-record coordinate they are made of. The crate had no guard at all
# before this, and it was the author of all four layouts.

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"

candidate=$(mktemp "${TMPDIR:-/tmp}/dclutch-generated.XXXXXX")
trap 'rm -f "$candidate"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.ProductAdmissionV2Abi >/dev/null
  lake env lean --run EmitProductAdmissionV2Rust.lean >"$candidate"
)

# Pinned literals chosen because a silent change to any of them is a wire
# change nothing else in this crate would notice: the three record widths, the
# coordinate stride, and the two coordinates the browser projects.
test "$(sed -n '1p' "$candidate")" = "// @generated by formal/dclutch-semantics/EmitProductAdmissionV2Rust.lean; do not edit."
grep -q '^pub const PRODUCT_RECORD_BYTES_V2: usize = 112;$' "$candidate"
grep -q '^pub const ADMISSION_REQUEST_BYTES_V2: usize = 112;$' "$candidate"
grep -q '^pub const ADMISSION_RECEIPT_BYTES_V2: usize = 400;$' "$candidate"
grep -q '^pub const RECORD_COORDINATE_BYTES: usize = 128;$' "$candidate"
grep -q '^pub const PRODUCT_DOMAIN_DIGEST_OFFSET: usize = 48;$' "$candidate"
grep -q '^pub const PRODUCT_PORTFOLIO_DIGEST_OFFSET: usize = 80;$' "$candidate"
test "$(wc -l <"$candidate" | tr -d ' ')" -ge 90

# The committed bytes are rustfmt output; normalize before comparing.
rustfmt --edition 2024 "$candidate"
cmp "$candidate" "$crate_dir/src/generated_admission_v2.rs"
