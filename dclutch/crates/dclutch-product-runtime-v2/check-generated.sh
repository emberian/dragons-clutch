#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/generated.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-product-runtime-v2.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.ProductRuntimeV2 DClutchSemantics.ProductRuntimeV2Abi
  lake env lean --run EmitProductRuntimeV2Rust.lean > "$temporary"
)

test "$(sed -n '1p' "$temporary")" = '// @generated by EmitProductRuntimeV2Rust.lean; do not edit.'
grep -q '^pub const DOMAIN_HEADER_BYTES: usize = 240;$' "$temporary"
grep -q '^pub const PORTFOLIO_HEADER_BYTES: usize = 208;$' "$temporary"
grep -q '^pub const REPRESENTATION_FLOOR_TAG: u8 = 1;$' "$temporary"
rustfmt --edition 2024 "$temporary"
cmp "$temporary" "$accepted"
