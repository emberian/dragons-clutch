#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/v2/generated.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-transition-v2.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.TransitionVMV2
  lake env lean --run EmitTransitionVMV2Rust.lean > "$temporary"
)

expected='// @generated by formal/dclutch-semantics/EmitTransitionVMV2Rust.lean; do not edit.'
test "$(sed -n '1p' "$temporary")" = "$expected"
# Counted on the emitter's RAW output, which is not the committed file's line
# count: the committed file is that output formatted (see the note below).
test "$(wc -l < "$temporary" | tr -d ' ')" -eq 42
# Normalise before comparing. The pins above read the emitter's RAW output; this
# compare reads it formatted, because the committed file is rustfmt's fixpoint.
# A raw compare holds `committed == emission` and so reds the first time anyone
# runs `tools/lane.sh fmt` on this `do not edit` file -- a direct rustfmt never
# sees the `#[rustfmt::skip]` that lives in the sibling module. That is not
# hypothetical (`ea4c46e02`), and it is why this pair sat in
# `tools/emission-guard/fixpoint-debt.tsv`.
rustfmt --edition 2024 "$temporary"
cmp "$temporary" "$accepted"
