#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/v2/generated.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-transition-v2.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.TransitionVMV2
  lake env lean --run EmitTransitionVMV2Rust.lean > "$temporary"
)

expected='// @generated by formal/dclutch-semantics/EmitTransitionVMV2Rust.lean; do not edit.'
test "$(sed -n '1p' "$temporary")" = "$expected"
test "$(wc -l < "$temporary" | tr -d ' ')" -eq 42
cmp "$temporary" "$accepted"
