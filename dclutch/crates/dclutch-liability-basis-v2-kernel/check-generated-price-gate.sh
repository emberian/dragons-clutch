#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/generated_price_gate.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-liability-basis-v2-price-gate.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.LiabilityBasisV2PriceGateAbi
  lake env lean --run EmitLiabilityBasisV2PriceGateRust.lean > "$temporary"
)

expected_header='// @generated by formal/dclutch-semantics/EmitLiabilityBasisV2PriceGateRust.lean; do not edit.'
test "$(sed -n '1p' "$temporary")" = "$expected_header"
test "$(sed -n '2p' "$temporary")" = 'use super::{PriceGateAgreementCaseV1, PriceGateRefusalCaseV1};'
# Counted on the emitter's RAW output, which is not the committed file's line
# count: the committed file is that output formatted (see the note below).
test "$(wc -l < "$temporary" | tr -d ' ')" -eq 457
grep -q '^pub static PRICE_GATE_AGREEMENT_CASES_V1: \[PriceGateAgreementCaseV1; 22\] = \[$' "$temporary"
grep -q '^pub static PRICE_GATE_REFUSAL_CASES_V1: \[PriceGateRefusalCaseV1; 45\] = \[$' "$temporary"
# Normalise before comparing: the committed file is rustfmt's fixpoint, so the
# pins above read the RAW emission and this compare reads the formatted one. A
# raw compare reds the first time `tools/lane.sh fmt` touches this file.
rustfmt --edition 2024 "$temporary"
cmp "$temporary" "$accepted"
