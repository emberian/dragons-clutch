use super::*;
use serde_json::json;

fn documents() -> (Vec<u8>, Vec<u8>) {
    let names = ["accepted-consume", "stale-ticket-refused"];
    let digest = "ab".repeat(32);
    let corpus = json!({"schema":"dclutch-series-consume-corpus-v1", "cases":names.map(|name| json!({"case":name,"input_sha256":digest}))});
    let result = json!({"schema":"dclutch-series-consume-result-v1", "cases":names.iter().enumerate().map(|(i,name)| json!({
        "case":name,"input_sha256":digest,"outcome":if i==0 {"accepted"} else {"refused"},
        "native_projection_sha256":digest,"interpreted_projection_sha256":digest,"shadow_projection_sha256":digest,
    })).collect::<Vec<_>>()});
    (
        serde_json::to_vec(&corpus).expect("corpus"),
        serde_json::to_vec(&result).expect("result"),
    )
}

fn evidence<'a>(corpus: &'a [u8], result: &'a [u8]) -> SeriesTranslationEvidenceV1<'a> {
    SeriesTranslationEvidenceV1 {
        semantic_source: b"consume owner",
        compiler_source_manifest: b"complete compiler source inventory",
        toolchain_manifest: b"toolchain",
        corpus,
        validator_source: b"comparison driver",
        validator_result: result,
        rustc_verbose: b"rustc test\n",
        cargo_lock: b"# This file is automatically @generated by Cargo.\n",
    }
}

#[test]
fn series_comparison_binds_every_case_source_and_executor() {
    let (corpus, result) = documents();
    let input = evidence(&corpus, &result);
    let checked =
        CheckedSeriesTranslationV1::build(input).expect("accepted and hostile comparisons");
    assert_eq!(
        CheckedSeriesTranslationV1::decode(&checked.encode()),
        Ok(checked)
    );
    assert_eq!(checked.verify(input), Ok(()));
    assert_eq!(
        checked.require_sources(
            input.semantic_source,
            input.compiler_source_manifest,
            input.toolchain_manifest
        ),
        Ok(())
    );
    assert_eq!(
        checked.require_sources(
            b"other semantic owner",
            input.compiler_source_manifest,
            input.toolchain_manifest
        ),
        Err(Error::CheckedTranslationValidationMismatch)
    );
    assert_eq!(
        checked.require_sources(
            input.semantic_source,
            b"other compiler",
            input.toolchain_manifest
        ),
        Err(Error::CheckedTranslationValidationMismatch)
    );
    assert_eq!(
        checked.require_sources(
            input.semantic_source,
            input.compiler_source_manifest,
            b"other toolchain"
        ),
        Err(Error::CheckedTranslationValidationMismatch)
    );

    let mut changed: Value = serde_json::from_slice(&result).expect("result");
    changed["cases"][0]["shadow_projection_sha256"] = Value::String("cd".repeat(32));
    let changed = serde_json::to_vec(&changed).expect("changed result");
    assert_eq!(
        CheckedSeriesTranslationV1::build(evidence(&corpus, &changed)),
        Err(Error::CheckedTranslationValidationMismatch)
    );
    assert_eq!(CheckedSeriesTranslationV1::build(input), Ok(checked));
}

#[test]
fn partial_misbound_and_refusal_only_runs_cannot_authorize_series() {
    let (corpus, result) = documents();
    let original: Value = serde_json::from_slice(&result).expect("result");
    for mutation in 0..7 {
        let mut value = original.clone();
        match mutation {
            0 => {
                value["cases"].as_array_mut().expect("cases").pop();
            }
            1 => value["cases"][0]["outcome"] = json!("refused"),
            2 => value["cases"][1]["outcome"] = json!("accepted"),
            3 => value["cases"][0]["input_sha256"] = json!("cd".repeat(32)),
            4 => value["cases"][0]["case"] = json!("another input"),
            5 => value["cases"][0]["outcome"] = json!("never-ran"),
            _ => value["schema"] = json!("dclutch-direct-translation-result-v1"),
        }
        let bytes = serde_json::to_vec(&value).expect("mutated result");
        assert_eq!(
            CheckedSeriesTranslationV1::build(evidence(&corpus, &bytes)),
            Err(Error::InvalidTranslationValidation),
            "mutation {mutation}"
        );
    }
    let checked =
        CheckedSeriesTranslationV1::build(evidence(&corpus, &result)).expect("control restored");
    let mut hostile = checked.encode();
    hostile[..8].copy_from_slice(b"DCLTTRV1");
    assert_eq!(
        CheckedSeriesTranslationV1::decode(&hostile),
        Err(Error::InvalidMagic)
    );
    hostile = checked.encode();
    hostile[12] = 1;
    assert_eq!(
        CheckedSeriesTranslationV1::decode(&hostile),
        Err(Error::InvalidTranslationValidation)
    );
    hostile = checked.encode();
    hostile[16..48].fill(0);
    assert_eq!(
        CheckedSeriesTranslationV1::decode(&hostile),
        Err(Error::ZeroIdentifier)
    );
    assert_eq!(
        CheckedSeriesTranslationV1::decode(&checked.encode()[..200]),
        Err(Error::InvalidLength)
    );
}

#[test]
fn duplicate_keys_and_noncanonical_documents_are_refused() {
    let (corpus, result) = documents();
    let text = String::from_utf8(result.clone()).expect("JSON");
    let duplicate = text.replacen(
        "\"outcome\":\"accepted\"",
        "\"outcome\":\"refused\",\"outcome\":\"accepted\"",
        1,
    );
    assert_ne!(duplicate, text);
    assert_eq!(
        CheckedSeriesTranslationV1::build(evidence(&corpus, duplicate.as_bytes())),
        Err(Error::InvalidTranslationValidation)
    );
    let pretty =
        serde_json::to_vec_pretty(&serde_json::from_slice::<Value>(&result).unwrap()).unwrap();
    assert_eq!(
        CheckedSeriesTranslationV1::build(evidence(&corpus, &pretty)),
        Err(Error::InvalidTranslationValidation)
    );
    let mut with_newline = result;
    with_newline.push(b'\n');
    CheckedSeriesTranslationV1::build(evidence(&corpus, &with_newline))
        .expect("one conventional final newline is accepted");
    with_newline.push(b'\n');
    assert_eq!(
        CheckedSeriesTranslationV1::build(evidence(&corpus, &with_newline)),
        Err(Error::InvalidTranslationValidation)
    );
}
