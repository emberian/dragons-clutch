"""The emission census and the wire-vector pins on a fixture tree: a guard counts only when it compares, a moved pin is red."""

from __future__ import annotations

import hashlib
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from gates import emission  # noqa: E402

HEADER = "// @generated by formal/dclutch-semantics/EmitFooRust.lean; do not edit.\n"


class EmissionTests(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="dclutch-emission-test."))
        subprocess.run(["git", "-C", str(self.root), "init", "-q"], check=True)
        (self.root / "crates/foo/src").mkdir(parents=True)
        (self.root / "crates/foo/tests").mkdir()
        (self.root / "crates/foo/Cargo.toml").write_text('[package]\nname = "foo"\n')
        (self.root / "crates/foo/src/generated.rs").write_text(HEADER + "pub const X: u8 = 1;\n")
        (self.root / "crates/bar").mkdir()
        (self.root / "crates/bar/orphan.rs").write_text("// @generated by formal/dclutch-semantics/EmitBarRust.lean; do not edit.\n")

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def add_all(self):
        subprocess.run(["git", "-C", str(self.root), "add", "-A"], check=True)

    def test_a_check_script_that_reruns_the_emitter_guards_its_file_and_an_orphan_is_unguarded(self):
        (self.root / "crates/foo/check-generated.sh").write_text("lake env lean --run EmitFooRust.lean | rustfmt --edition 2024 | cmp - src/generated.rs\n")
        self.add_all()
        census = emission.build_census(self.root)
        guarded, unguarded = census.split()
        self.assertEqual(set(guarded), {"crates/foo/src/generated.rs"})
        self.assertEqual(set(unguarded), {"crates/bar/orphan.rs"})
        self.assertTrue(census.guards[0].normalises)

    def test_a_rust_test_counts_only_when_it_reads_back_and_compares(self):
        (self.root / "crates/foo/tests/fresh.rs").write_text('fn t() { Command::new("lake").args(["env", "lean", "--run", "EmitFooRust.lean"]); }\n')
        self.add_all()
        self.assertEqual(emission.build_census(self.root).guards, [])
        (self.root / "crates/foo/tests/fresh.rs").write_text(
            '// rustfmt is deliberately NOT run here\nfn t() { let out = run("EmitFooRust.lean"); assert_eq!(out, fs::read("src/generated.rs").unwrap()); }\n')
        self.add_all()
        guards = emission.build_census(self.root).guards
        self.assertEqual(len(guards), 1)
        self.assertEqual(guards[0].kind, "cargo-test")
        self.assertFalse(guards[0].normalises, "a comment naming rustfmt is not an invocation")

    def test_pins_refuse_a_moved_fixture_and_repin_writes_the_new_digest(self):
        fixture = self.root / "fixtures/v.json"
        fixture.parent.mkdir()
        fixture.write_text("reviewed\n")
        pins = self.root / "pins.tsv"
        pins.write_text(f"# header\n{hashlib.sha256(fixture.read_bytes()).hexdigest()}\tfixtures/v.json\tsome --test\n")
        self.assertEqual(emission.pins(self.root, pins_path=pins), 0)
        fixture.write_text("moved\n")
        self.assertEqual(emission.pins(self.root, pins_path=pins), 1)
        self.assertEqual(emission.pins(self.root, repin=True, pins_path=pins), 0)
        self.assertIn(hashlib.sha256(b"moved\n").hexdigest(), pins.read_text())
        self.assertTrue(pins.read_text().startswith("# header\n"))
        fixture.unlink()
        self.assertEqual(emission.pins(self.root, pins_path=pins), 1, "a missing fixture is red, not re-pinned")


if __name__ == "__main__":
    unittest.main()
