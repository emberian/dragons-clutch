"""Emit a cohort's job-directory stage scripts as ONE family, from the runbook.

Cohort-15 ran from 33 hand-written scripts naming 82 absolute paths and 134
flags the runbook did not carry, in four structural shapes -- a bounded wait, an
attempt loop, guard-exits, and one script waiting on another's log. Every one of
those is now a column: the flags are `args`, the shapes are `shape`, and the
peer-chaining is `blocks`. This generator is where they become bash.

Every emitted script:

  * resolves everything from `$HERE` -- the job directory is the unit, and a
    path into a build scratch is not in it. Enforced, not intended: the
    self-contained value test below refuses to leave a script naming any
    absolute path, and `test.sh` proves it red.
  * resolves the driver from `$HERE/bin` and CHECKS ITS DIGEST against the
    `.sha256` staging wrote beside it, so a swapped driver is refused rather
    than run.
  * reads the endpoint credential AT USE TIME from the environment. No file
    here holds it, and none ever prints it.
  * REFUSES TO START until every row that `blocks` it has left its GREEN
    marker -- a stage chained behind a settle no longer greps another script's
    log to find out whether the settle landed.
  * BACKS UP BEFORE IT ATTEMPTS. An output that exists is copied under
    `$HERE/backups/<stage>/` with the attempt's Unix time before anything
    overwrites it.
  * carries THE VERIFIER THE ROW NAMES, as the thing to check, in words, and
    writes its GREEN marker only when its last invocation exited zero. The exit
    code is not the verifier; this repository has paid for that three times in
    one day.

A row whose `args` are `-` is emitted as a script that refuses with the
sentence "this row carries no args yet", so the count of those is visible in
the job directory rather than in a lane's memory. A row that names `{market.x}`
is emitted once per market of the kind its stage implies; the manifest's
`markets` list is the authority for how many.

usage: generate-stage-scripts.py --cohort 15 --out <dir> [--delta]
"""

