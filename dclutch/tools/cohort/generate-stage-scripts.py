class Emission(Exception):
    pass


def market_kinds(key: str) -> tuple[str, ...]:
    return MARKET_KIND.get(key, DEFAULT_KINDS)


def per_market(row: dict) -> bool:
    """A row fans out over markets if it names a market field OR waits on a
    market's own schedule -- a `wait:` row reads `{market.window_record}` from
    the template rather than from its args, and would otherwise emit once with
    no market."""
    return "{market." in row["args"] or row["shape"].startswith("wait:")


def lookup_or_refuse(document: dict, dotted: str, where: str):
    value = check_steps.lookup(document, dotted)
    if value is None:
        raise Emission(f"{where}: the manifest has no field {dotted!r}")
    return value


def expand_inline_loops(text: str, document: dict, market: dict | None, where: str) -> str:
    """`@roles{ ... }`, `@owned_roles{ ... }`, `@list:a.b{ ... }` -> repeated text."""
    out = []
    i = 0
    while True:
        match = check_steps.INLINE_LOOP.search(text, i)
        if not match:
            out.append(text[i:])
            break
        out.append(text[i:match.start()])
        depth, j = 1, match.end()
        while j < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        body = text[match.end():j - 1]
        head = match.group(0)[1:-1]
        if head == "roles":
            items = [(role, {"role": role, "role_flag": ROLE_FLAG.get(role, role)}) for role in document["roles"]]
        elif head == "owned_roles":
            items = [(role, {"role": role, "role_flag": ROLE_FLAG.get(role, role)}) for role in document["owned_roles"]]
        else:
            dotted = head[len("list:"):]
            if dotted.startswith("market."):
                if market is None:
                    raise Emission(f"{where}: {{{dotted}}} needs a market")
                node = market
                for part in dotted.split(".")[1:]:
                    node = node.get(part) if isinstance(node, dict) else None
                    if node is None:
                        raise Emission(f"{where}: market {market.get('label')} has no field {dotted!r}")
            else:
                node = lookup_or_refuse(document, dotted, where)
            if not isinstance(node, list):
                raise Emission(f"{where}: {dotted!r} is not a list")
            items = [(str(item), {"item": str(item)}) for item in node]
        rendered = []
        for _, scope in items:
            piece = body
            for name, value in scope.items():
                piece = piece.replace("{" + name + "}", value)
            rendered.append(piece.strip())
        out.append(" ".join(rendered))
        i = j
    return "".join(out)


def substitute(text: str, document: dict, prior: dict | None, market: dict | None,
               scope: dict[str, str], stages: dict[str, str], where: str) -> str:
    text = expand_inline_loops(text, document, market, where)
    # The loop-scope names (`{role}`, `{participant}`, ...) are resolved by
    # TEXT replacement first, so a single placeholder pass then resolves
    # `{programs.custody}` and `{pubkey:keys/participant-1.json}` -- and never
    # re-scans the bash it just emitted for `{execute}` (a `${EXTRA[@]...}`
    # brace is not a placeholder).
    for name, value in scope.items():
        text = text.replace("{" + name + "}", value)

    def one(match):
        raw = match.group(1)
        if raw == "mode":
            return "$MODEWORD"
        if raw == "attempt":
            return "$attempt"
        if raw == "execute":
            return '${EXTRA[@]+"${EXTRA[@]}"}'
        if raw.startswith("execute:"):
            # DOUBLE QUOTES, because the payload carries $HERE. Single-quoted,
            # `--fee-payer-keypair $HERE/keys/campaign-payer.json` reached the
            # driver with the four characters `$HERE` in it and earned "fee
            # settlement payer keypair path must be absolute" -- a refusal about
            # a path that was never a path. The outer $( ) is deliberately
            # unquoted so the payload still splits into separate arguments; the
            # generator already refuses absolute paths, and a job directory with
            # a space in its name would be caught by the self-contained test.
            payload = raw[len("execute:"):]
            if '"' in payload:
                raise Emission(f"{where}: an {{execute:…}} payload may not contain a double quote")
            return '$( [ "$MODE" = --execute ] && printf %s "' + payload + '" )'
        if raw.startswith("pubkey:"):
            path = one(check_steps.PLACEHOLDER.fullmatch(raw[len("pubkey:"):])) if raw[len("pubkey:"):].startswith("{") else raw[len("pubkey:"):]
            return '$(solana-keygen pubkey "$HERE/' + path + '")'
        if raw.startswith("stage:"):
            key = raw[len("stage:"):]
            if key not in stages:
                raise Emission(f"{where}: {{stage:{key}}} names a row this cohort does not run")
            return "$HERE/" + stages[key]
        if raw.startswith("market."):
            if market is None:
                raise Emission(f"{where}: {{{raw}}} used in a row with no market")
            node = market
            for part in raw.split(".")[1:]:
                node = node.get(part) if isinstance(node, dict) else None
                if node is None:
                    raise Emission(f"{where}: market {market.get('label')!r} has no field {raw!r}; record it in the manifest and regenerate")
            if not isinstance(node, (str, int)):
                raise Emission(f"{where}: market field {raw!r} is not a value")
            return str(node)
        if raw.startswith("prior."):
            if prior is None:
                raise Emission(f"{where}: {{{raw}}} needs cohorts/{document['prior_cohort']}.json")
            field = raw[len("prior."):]
            if field == "job_dirname":
                return pathlib.PurePath(prior["job_dir"]).name
            value = check_steps.lookup(prior, field)
            if value is None:
                raise Emission(f"{where}: the prior manifest has no field {field!r}")
            return str(value)
        return str(lookup_or_refuse(document, raw, where))

    # Innermost-first to a fixpoint, so `{pubkey:{market.fill.debtor_keypair}}`
    # resolves the inner name and then the outer. A `{` preceded by `$` is a
    # bash parameter expansion (`${ARG2:+--prior ...}`, and the `${EXTRA[@]...}`
    # an `{execute}` expands to), never a placeholder -- so re-scanning the
    # emitted output leaves it alone. A `{...}` body may hold `:` and `/`, which
    # the gate's plainer placeholder does not match; this generator has its own.
    pattern = re.compile(r"(?<!\$)\{([^{}]+)\}")
    for _ in range(6):
        new = pattern.sub(one, text)
        if new == text:
            break
        text = new
    return text


def command_line(kind: str, rest: str, document: dict) -> str:
    if kind == "bootstrap":
        return '"$DRIVER" ' + rest.replace(" ", ' --rpc-url "$DCLUTCH_RPC_URL" --i-mean-devnet "$GENESIS" ', 1) if " " in rest else '"$DRIVER" ' + rest
    if kind == "bootstrap-public":
        sub, _, tail = rest.partition(" ")
        return f'"$DRIVER" {sub} --rpc-url {document["cluster"]["public_url"]} --i-mean-devnet "$GENESIS" {tail}'
    if kind == "bootstrap-offline":
        return '"$DRIVER" ' + rest
    if kind == "solana":
        sub = rest.split(" ")
        # `--url` rides after the subcommand words (`program deploy`, `transfer`).
        words = 2 if sub[0] in ("program", "address-lookup-table", "stake") else 1
        return '"$CLI" ' + " ".join(sub[:words]) + ' --url "$DCLUTCH_RPC_URL" ' + " ".join(sub[words:])
    if kind == "script":
        path, _, tail = rest.partition(" ")
        runner = "python3" if path.endswith(".py") else "bash"
        return f'{runner} "$DCLUTCH_REPO/{path}" {tail}'
    if kind == "simulator":
        return f'python3 "$DCLUTCH_REPO/tools/load-simulator/simulator.py" {rest}'
    if kind == "sh":
        return rest
    raise Emission(f"driver kind {kind!r} has no emission")


def emit(row, view_step, document, prior, market, stages) -> str:
    key = row["key"]
    stage = view_step["stage"]
    slug = re.sub(r"[^a-z0-9-]+", "-", stage.lower()).strip("-")
    label = market["label"] if market else None
    stage_dir = f"{key}-{label}" if market else key
    where = f"{key}" + (f" (market {label})" if market else "")

    lines = ["#!/usr/bin/env bash", MARKER, "#",
             f"# {view_step['id']} {stage}   (runbook key: {key}, since cohort {row['since']}"
             + (f", market {label}" if market else "") + ")",
             "#", "# WHAT THIS DOES"]
    lines += wrap(view_step["command"])
    lines += ["#", "# THE VERIFIER, WHICH IS WHAT SAYS THIS RAN -- not the exit code:"]
    lines += wrap(view_step["verifier"])
    if view_step["blocks"] != "-":
        lines += ["#", "# Nothing at step " + view_step["blocks"] + " may start until this is green."]
    if view_step["cost"] != "-":
        lines += ["#", f"# Priced from cohort-{document['prior_cohort']}'s own ledger: {view_step['cost']} SOL."]
    lines.append("")
    head = "\n".join(lines)

    if row["shape"] == "commit":
        what = "\n".join(f'echo "  {line[4:]}" >&2' for line in wrap(view_step["command"], prefix="#   "))
        return head + COMMIT % {"stage_literal": f'"{stage_dir}"', "what": what}
    if row["args"] == "-":
        return head + NO_ARGS % {"stage_literal": f'"{stage_dir}"'}

    # The guards: every row that blocks THIS row must have left GREEN.
    blockers = [r["key"] for r in row["_chosen"] if row["key"] in [b.strip() for b in r["blocks"].split(",")]]
    guards = []
    for blocker in blockers:
        for bdir in stages_for(blocker, row["_chosen"], document, label):
            guards.append(f'[ -f "$HERE/{bdir}/GREEN" ] || {{ echo "$STAGE: {bdir} has not gone green; nothing here may start until it has" >&2; exit 65; }}')
    if not guards:
        guards.append("# (nothing blocks this row)")

    invs = check_steps.invocations(row["args"])
    kinds = {check_steps.invocation_parts(t)[3].split(" ", 1)[0] for t in invs}
    needs_endpoint = kinds & {"bootstrap", "bootstrap-public", "solana", "script", "simulator", "sh"} or row["shape"] in check_steps.LOOPING
    needs_driver = kinds & {"bootstrap", "bootstrap-public", "bootstrap-offline"} or row["shape"] in check_steps.LOOPING
    needs_cli = "solana" in kinds or "programdata" in row["args"] or "$CLI" in row["args"]
    needs_repo = kinds & {"script", "simulator"}
    helpers = ""
    if needs_endpoint:
        helpers += ENDPOINT % {"genesis": document["cluster"]["genesis_hash"]}
    if needs_cli:
        helpers += SOLANA_CLI % {"cli_env": document["host"]["solana_cli_env"]}
    if needs_driver:
        helpers += DRIVER_BOOTSTRAP % {"binary": DRIVER_BINARY}
    if needs_repo:
        helpers += REPO % {"repo_env": document["host"]["repo_env"]}
    for var in sorted(set(re.findall(r"\$(DCLUTCH_[A-Z_]+)", row["args"])) - {"DCLUTCH_RPC_URL", "DCLUTCH_REPO"}):
        helpers += f': "${{{var}:?required by this stage}}"\n'

    body = PREAMBLE % {"stage_literal": f'"{stage_dir}"', "guards": "\n".join(guards), "helpers": helpers}

    roles = document["roles"] if row["shape"] == "per-role" else [None]
    acts: list[tuple[str, str | None]] = []
    plain: list[str] = []
    for role in roles:
        scope = {"role": role, "role_flag": ROLE_FLAG.get(role, role)} if role else {}
        for text in invs:
            loop, act, skip, rest = check_steps.invocation_parts(text)
            done_spec = None
            m = check_steps.ACT.match(text.split(" ", 1)[1] if loop else text)
            if act and m and m.group(0).strip().startswith("*["):
                done_spec = m.group(0).strip()[2:-1]
            kind, _, tail = rest.partition(" ")
            repeats: list[dict[str, str]]
            if loop == "@roles":
                repeats = [{"role": r, "role_flag": ROLE_FLAG.get(r, r)} for r in document["roles"]]
            elif loop == "@owned_roles":
                repeats = [{"role": r, "role_flag": ROLE_FLAG.get(r, r)} for r in document["owned_roles"]]
            elif loop == "@participants":
                repeats = [{"participant": p} for p in document["payer"]["participant_keypairs"]]
            else:
                repeats = [{}]
            for extra in repeats:
                line = command_line(kind, substitute(tail, document, prior, market, {**scope, **extra}, stages, where), document)
                if act:
                    acts.append((line, substitute(done_spec, document, prior, market, {**scope, **extra}, stages, where) if done_spec else None))
                    continue
                if skip:
                    # THE PATH A `?` CHECKS IS THE ROW'S OWN OUTPUT, WHICH IS
                    # ALWAYS UNDER $OUT. Taking the first write-shaped flag was
                    # wrong the moment a row also READ one: `arm-relay` passes
                    # `--evidence $HERE/<market>/campaign-open.json`, the
                    # founding's report, before its `--output $OUT/...`, so both
                    # invocations announced "present, not overwriting" about an
                    # input that had of course been there since the founding,
                    # and the stage produced nothing. Measured on cohort-17.
                    candidates = [(m.group(1), m.group(2)) for m in re.finditer(
                        r"--(output|evidence|out|completion)(?:-dir)?\s+(\S+)", line)]
                    named = [v for f, v in candidates if f != "evidence"] \
                        or [v for f, v in candidates]
                    if not named:
                        raise Emission(f"{where}: a `?` invocation names no --output/--evidence to check")
                    line = f'if [ -e "{named[0]}" ]; then echo "{named[0]} present, not overwriting"; else {line}; fi'
                else:
                    output = re.search(r"--(output|evidence|out|completion)(-dir)?\s+(\S+)", line)
                    if output and output.group(3).startswith("$OUT"):
                        path = output.group(3)
                        # A DIRECTORY THIS ROW MUST HAND THE DRIVER HAS TO SURVIVE
                        # ITS OWN BACKUP. `--output-dir` is emptied for the fresh
                        # attempt and then recreated, because the driver refuses
                        # "No such file or directory" on an absent one -- the
                        # preamble's mkdir and this rm otherwise cancel out, which
                        # is what cohort-17 measured.
                        remake = ""
                        if output.group(2) and output.group(1) not in FRESH_DIRECTORY_FLAGS \
                           and f"{output.group(1)}-dir" not in FRESH_DIRECTORY_FLAGS:
                            remake = f'; mkdir -p "{path}"'
                        line = f'backup "{path}"; rm -rf "{path}"{remake}\n{line}'
                plain.append(line)

    # A ROW THAT WRITES OUTSIDE $OUT HAS TO BE ALLOWED TO. The preamble creates
    # $OUT and the backup directory and nothing else, so `prepare` -- whose
    # `--output-file $HERE/observed/<role>.programdata.bin` is the runbook's own
    # words -- died on the FIRST role with "No such file or directory (os error
    # 2)" and no name for what was missing.
    #
    # ONLY THE PARENT, NEVER THE DIRECTORY ITSELF. `prepare --account-dir
    # $HERE/accounts` creates its own account directory and REFUSES one that
    # already exists ("create fresh account directory ...: File exists"), so a
    # generator that made the leaf would trade one refusal for another. The
    # parents are derived from the row's own write flags rather than listed.
    written = set()
    for line, _ in acts + [(t, None) for t in plain]:
        for flag, value in re.findall(r"--([a-z-]*(?:output|evidence|completion|campaign|journal|account|dump|receipt)[a-z-]*)\s+(\S+)", line):
            if not (value.startswith("$HERE/") or value.startswith("$OUT/")):
                continue
            # A `-dir` flag names a directory, and the two drivers that take one
            # want OPPOSITE things: `devnet-direct-trade-produce-v1 --output-dir`
            # refuses "No such file or directory" when it is absent, and
            # `prepare --account-dir` refuses "create fresh account directory:
            # File exists" when it is present. Both measured on cohort-17. So
            # the leaf is created for every write directory except the ones a
            # driver insists on creating itself, and that set is named here
            # rather than guessed from the flag's shape.
            parent = value if (flag.endswith("-dir") and flag not in FRESH_DIRECTORY_FLAGS) \
                else value.rsplit("/", 1)[0]
            if parent not in ("$HERE", "$OUT"):
                written.add(parent)
    if written:
        body += "# Every directory this row's own write flags name, and no other.\n"
        body += "mkdir -p " + " ".join(f'"{d}"' for d in sorted(written)) + "\n"

    if row["shape"] in ("once", "per-role"):
        body += "\n" + "\n".join(plain) + "\n"
    elif row["shape"] in ("attempts", "wait:capture", "wait:settle"):
        before = plain
        if row["shape"].startswith("wait:"):
            phase = row["shape"][5:]
            body += WAIT % {"ceiling": 2000, "phase": phase,
                            "window": substitute("{market.window_record}", document, prior, market, {}, stages, where),
                            "window_guard": WINDOW_GUARD_CAPTURE if phase == "capture" else WINDOW_GUARD_SETTLE}
        if before:
            body += "\n" + "\n".join(before) + "\n"
        for line, _ in acts:
            act_label = re.search(r"--action\s+(\S+)", line)
            act_label = act_label.group(1) if act_label else "act"
            body += ATTEMPT_LOOP % {"attempts": ATTEMPTS, "label": act_label, "upper": act_label.upper().replace("-", "_"),
                                    "plan": "    " + line, "sign": "    " + line}
    elif row["shape"] == "journal":
        if plain:
            body += "\n" + "\n".join(plain) + "\n"
        for line, done in acts:
            if not done:
                raise Emission(f"{where}: a journal act must name what says it is done: *[FILE] or *[FILE:field,field]")
            path, _, fields = done.partition(":")
            if fields:
                checks = " and ".join(f'd.get("{f}") is not None' for f in fields.split(","))
                done_test = f'[ -f "{path}" ] && python3 -c \'import json,sys; d=json.load(open(sys.argv[1])); sys.exit(0 if ({checks}) else 1)\' "{path}"'
            else:
                done_test = f'[ -f "{path}" ]'
            journal_dir = re.search(r"--journal-dir\s+(\S+)", line)
            act_label = re.search(r'"\$DRIVER" (\S+)', line)
            act_label = (act_label.group(1) if act_label else "act").replace("devnet-", "").replace("-v1", "")
            body += JOURNAL_LOOP % {"passes": JOURNAL_PASSES, "label": act_label, "upper": act_label.upper().replace("-", "_"),
                                    "act": line, "done_test": done_test,
                                    "journal_dir": journal_dir.group(1) if journal_dir else "$OUT"}
    else:
        raise Emission(f"{where}: shape {row['shape']!r} has no emission")

    body += f'\ntouch "$OUT/GREEN"\necho "{stage_dir.upper().replace("-", "_")}_EXIT=0"\n'
    return head + body


def stages_for(key: str, chosen: list[dict], document: dict, label: str | None) -> list[str]:
    """The output directories a row emits: one, or one per market it fans over."""
    row = next((r for r in chosen if r["key"] == key), None)
    if row is None:
        return []
    if not per_market(row):
        return [key]
    kinds = market_kinds(key)
    # A per-market row blocking a per-market row binds the SAME market; a
    # per-market row blocking a one-shot row means all of its markets.
    markets = [m for m in document.get("markets", []) if m.get("kind", "direct") in kinds]
    if label is not None and any(m["label"] == label for m in markets):
        return [f"{key}-{label}"]
    return [f"{key}-{m['label']}" for m in markets]


def selfcontained(path: pathlib.Path) -> list[str]:
    offenders = []
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if number == 1 and line.startswith("#!"):
            continue
        for match in ABSOLUTE.finditer(line):
            if match.group(0) in ALLOWED_ABSOLUTE:
                continue
            offenders.append(f"{path.name}:{number}: {match.group(0)}")
    return offenders


def credentialfree(path: pathlib.Path) -> list[str]:
    text = path.read_text()
    return [f"{path.name}: holds an endpoint credential"] if re.search(r"https?://[^\s\"']*[?@]", text) else []


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cohort", required=True)
    parser.add_argument("--out", required=True, help="a job directory; refuses to clobber hand-written scripts")
    parser.add_argument("--delta", action="store_true")
    arguments = parser.parse_args()

    document = check_steps.manifest(arguments.cohort)
    prior_path = check_steps.COHORTS / f"{document.get('prior_cohort')}.json"
    prior = json.loads(prior_path.read_text()) if prior_path.exists() else None
    table = check_steps.rows()
    problems: list[str] = []
    check_steps.structural(table, problems)
    chosen = check_steps.select(table, int(document["cohort"]), arguments.delta)
    view = check_steps.render(table, chosen, document, problems)
    if problems:
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    for row in chosen:
        row["_chosen"] = chosen

    out = pathlib.Path(arguments.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    # THE LIVE JOB DIRECTORY IS NOT OURS TO REWRITE. A hand-written stage script
    # is a cohort in flight; refusing here is cheaper than a lane discovering it.
    for existing in sorted(out.glob("*.sh")):
        if MARKER not in existing.read_text():
            print(f"refusing to write beside a hand-written script: {existing.name}", file=sys.stderr)
            return 2

    written, offences, unemitted = [], [], []
    try:
        for row, step in zip(chosen, view):
            markets = [None]
            if per_market(row):
                markets = [m for m in document.get("markets", []) if m.get("kind", "direct") in market_kinds(row["key"])]
                if not markets:
                    print(f"  {row['key']}: no market of kind {market_kinds(row['key'])} in the manifest; not emitted")
                    continue
            stages = {r["key"]: (r["key"] + "-{label}" if per_market(r) else r["key"]) for r in chosen}
            for market in markets:
                bound = {k: v.replace("{label}", market["label"] if market else "") for k, v in stages.items()}
                suffix = f"-{market['label']}" if market else ""
                path = out / f"{step['id']}-{row['key']}{suffix}.sh"
                path.write_text(emit(row, step, document, prior, market, bound))
                path.chmod(path.stat().st_mode | stat.S_IXUSR)
                written.append(path)
                offences += selfcontained(path) + credentialfree(path)
                if row["args"] == "-" and row["shape"] != "commit":
                    unemitted.append(row["key"])
    except Emission as refusal:
        print(f"refusing: {refusal}", file=sys.stderr)
        for path in written:
            path.unlink()
        return 2

    if offences:
        # A generator that merely INTENDS not to write a secret or a stranding
        # path, and one that checks, log identically. So it checks, every time,
        # and removes what it wrote rather than leaving it to be trusted.
        print("refusing to leave a job directory whose scripts depend on paths outside it:", file=sys.stderr)
        for offence in offences:
            print(f"  {offence}", file=sys.stderr)
        for path in written:
            path.unlink()
        return 2

    print(f"cohort-{document['cohort']}{' delta' if arguments.delta else ''}: "
          f"{len(written)} stage scripts, 0 absolute paths, 0 credentials, "
          f"{len(unemitted)} rows carrying no args yet" + (f" ({', '.join(unemitted)})" if unemitted else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
