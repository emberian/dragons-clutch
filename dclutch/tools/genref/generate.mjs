// -------------------------------------------------- route execution status

// route id -> [{campaign, outcome, refusal?, file}]
const routeEvidence = new Map();
// binding route refs that match no inventory route id
const unknownRefs = [];

const inventoryRouteIds = new Set();
for (const p of programs) for (const r of p.routes) inventoryRouteIds.add(r.id);

for (const file of bindingsFiles) {
  const rel = path.relative(REPO, file);
  const data = readJSON(file);
  for (const b of data.bindings ?? []) {
    for (const ref of b.routes ?? []) {
      if (!inventoryRouteIds.has(ref)) {
        unknownRefs.push({ ref, file: rel, label: b.label });
        continue;
      }
      if (!routeEvidence.has(ref)) routeEvidence.set(ref, []);
      routeEvidence.get(ref).push({
        campaign: data.campaign ?? rel,
        outcome: b.outcome ?? "?",
        file: rel,
      });
    }
  }
}

// blocked.json: most specific matching rule wins; trailing '*' is a prefix
// glob (the file's own stated rules).
const blockedRules = blocked.blocked.map((b) => ({
  route: b.route,
  reason: b.reason,
}));
function blockedRuleFor(routeId) {
  let best = null;
  for (const rule of blockedRules) {
    if (rule.route.endsWith("*")) {
      const prefix = rule.route.slice(0, -1);
      if (routeId.startsWith(prefix)) {
        if (!best || rule.route.length > best.route.length) best = rule;
      }
    } else if (rule.route === routeId) {
      return rule; // exact always wins
    }
  }
  return best;
}

function firstSentence(s) {
  const m = s.match(/^(.*?\.)(\s|$)/s);
  return (m ? m[1] : s).replaceAll("\n", " ");
}

function routeStatus(routeId) {
  const ev = routeEvidence.get(routeId);
  if (ev) {
    const parts = [...new Set(ev.map((e) => `${e.outcome} (${e.campaign})`))]
      .sort();
    return { kind: "witnessed", text: parts.join("; ") };
  }
  const rule = blockedRuleFor(routeId);
  if (rule) {
    return {
      kind: "blocked",
      text: `blocked by rule \`${rule.route}\`: ${firstSentence(rule.reason)}`,
    };
  }
  return { kind: "none", text: "NEVER-EXECUTED, no stated reason" };
}

// ------------------------------------------------------ refusal band table

// Parse `/// Band ... .` doc lines paired with `pub const *_BASE: u32 = ...;`
const bandRows = [];
{
  const lines = registrySource.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(
      /^pub const ([A-Z0-9_]+(?:_BASE|_REFUSAL_BASE)): u32 = (0x[0-9A-Fa-f_]+);/,
    );
    if (!m) continue;
    // walk back over the doc comment block
    let doc = [];
    for (let j = i - 1; j >= 0; j--) {
      const dm = lines[j].match(/^\/\/\/ ?(.*)$/);
      if (!dm) break;
      doc.unshift(dm[1]);
    }
    const docText = doc.join(" ").trim();
    if (!/^Band /.test(docText)) continue;
    const base = parseInt(m[2].replaceAll("_", ""), 16);
    bandRows.push({
      constant: m[1],
      base,
      band: base >> 12,
      doc: docText.replace(/\.$/, ""),
    });
  }
  bandRows.sort((a, b) => a.base - b.base);
}

