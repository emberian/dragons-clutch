// -------------------------------------------------- route execution status

// route id -> [{campaign, outcome, refusal?, file}]
const routeEvidence = new Map();
// Refusal id -> the campaigns whose folded evidence carried it. Derived from
// the same bindings the census folds, never typed: `census observe` refuses to
// admit a `refused` binding unless the chain's own `Program <id> failed:
// custom program error: 0xN` line reports that exact code AND the program the
// refusal id names raised it. So a refusal id reaching this map has fired on a
// real ELF, or its tier is red.
const refusalEvidence = new Map();
// Refusals a campaign observed but credited to no enumerated code. They are
// real refusals and deliberately NOT counted as an observed code.
let uncreditedRefusals = 0;
// binding route refs that match no inventory route id
const unknownRefs = [];

const inventoryRouteIds = new Set();
for (const p of programs) for (const r of p.routes) inventoryRouteIds.add(r.id);

for (const file of bindingsFiles) {
  const rel = path.relative(REPO, file);
  const data = readJSON(file);
  for (const b of data.bindings ?? []) {
    for (const ref of b.routes ?? []) {
      if (!inventoryRouteIds.has(ref)) {
        unknownRefs.push({ ref, file: rel, label: b.label });
        continue;
      }
      if (!routeEvidence.has(ref)) routeEvidence.set(ref, []);
      routeEvidence.get(ref).push({
        campaign: data.campaign ?? rel,
        outcome: b.outcome ?? "?",
        file: rel,
      });
    }
    if (b.outcome === "refused") {
      if (b.refusal) {
        if (!refusalEvidence.has(b.refusal)) refusalEvidence.set(b.refusal, []);
        refusalEvidence.get(b.refusal).push({
          campaign: data.campaign ?? rel,
          file: rel,
        });
      } else if (b.unnamed_refusal) {
        uncreditedRefusals += 1;
      }
    }
  }
}

// ------------------------------------------------ the substrate of a witness

// `routes.md` says "witnessed" and means "a campaign binding names it". That
// sentence hides three different evidence levels behind one word: the C-16
// rehearsal sorted the same 101 witnessed rows and found 0 on devnet, 19 on a
// validator and 57 on an in-process ProgramTest bank. The register could not
// print the difference because nothing in the tree recorded which substrate a
// campaign ran on. `tools/gauntlet/substrates.json` records it, one row per
// campaign, and this is where it is CHECKED -- a declaration nobody verifies is
// the mirror the census exists to refuse.
const SUBSTRATE_RANK = {
  none: 0,
  "program-test": 1,
  "local-validator": 2,
  devnet: 3,
};

const substratesFile = path.join(gauntletDir, "substrates.json");
const substrates = readJSON(substratesFile);
const substrateFor = new Map();
for (const row of substrates.campaigns) {
  substrateFor.set(row.campaign, row);
}

{
  const problems = [];
  const declared = new Set(substrateFor.keys());
  const bound = new Set();
  for (const file of bindingsFiles) {
    bound.add(readJSON(file).campaign ?? path.relative(REPO, file));
  }
  for (const campaign of [...bound].sort()) {
    if (!declared.has(campaign)) {
      problems.push(
        `campaign \`${campaign}\` binds routes but has no row in tools/gauntlet/substrates.json. ` +
          `Add one naming its substrate (${Object.keys(SUBSTRATE_RANK).join(" | ")}), its runner and its producer.`,
      );
    }
  }
  for (const campaign of [...declared].sort()) {
    const row = substrateFor.get(campaign);
    if (!bound.has(campaign)) {
      problems.push(
        `tools/gauntlet/substrates.json declares \`${campaign}\`, which binds no route in any bindings.json. ` +
          `A stale row looks exactly like a live one from the register.`,
      );
    }
    if (!(row.substrate in SUBSTRATE_RANK) || row.substrate === "none") {
      problems.push(`\`${campaign}\`: substrate \`${row.substrate}\` is not one of the declared classes`);
    }
    if (row.reproducible !== true && typeof row.reproducible !== "string") {
      problems.push(
        `\`${campaign}\`: \`reproducible\` must be true or a sentence saying what stops the ` +
          `campaign completing. A campaign that no longer runs has to have somewhere to say so.`,
      );
    }
    for (const key of ["runner", "producer"]) {
      const rel = row[key];
      if (rel !== null && !fs.existsSync(path.join(REPO, rel))) {
        problems.push(`\`${campaign}\`: ${key} \`${rel}\` does not exist`);
      }
    }
    // The positive control. A campaign that says `local-validator` must reach
    // one; a campaign that says `program-test` must not. Without this the
    // substrate column is one more authored sentence, and an authored sentence
    // is the thing this page exists to stop being the only evidence.
    //
    // It used to be `runner.includes("solana-test-validator")` over the raw
    // file, and `tools/gauntlet/lineage/run-lineage.sh` passed it on a COMMENT
    // — a control that could not fail for the reason it exists. It now strips
    // shell comments and follows the scripts the runner invokes one level down,
    // which is where that campaign's validator actually lives. See
    // tools/genref/substrate-control.mjs for what it does and does not claim.
    if (row.runner) {
      const control = launchesLocalValidator(REPO, row.runner);
      if (row.substrate === "local-validator" && !control.launches) {
        problems.push(
          `\`${campaign}\`: declared local-validator, but no executable text in ` +
            `${control.searched.join(", ")} names ${VALIDATOR_TOKEN} ` +
            `(comments do not count, and only scripts the runner invokes are followed)`,
        );
      }
      if (row.substrate === "program-test" && control.launches) {
        problems.push(
          `\`${campaign}\`: declared program-test, but ${control.sites.join(", ")} ` +
            `names ${VALIDATOR_TOKEN} in executable text`,
        );
      }
    }
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(`genref: ${problem}`);
    console.error(
      "genref: tools/gauntlet/substrates.json does not describe this tree's campaigns.",
    );
    process.exit(1);
  }
}

