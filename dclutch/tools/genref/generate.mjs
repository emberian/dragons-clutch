// Parse one machine-emitted TS module into typed constants. Anything the
// parser does not recognize is carried verbatim into an "unrendered" bucket
// rather than dropped: the reference must not silently narrow its source.
function parseTsModule(name) {
  const text = read(path.join(generatedTsDir, name));
  const headerLines = [];
  for (const line of text.split("\n")) {
    if (line.startsWith("//")) headerLines.push(line.replace(/^\/\/ ?/, ""));
    else if (line.trim() === "") continue;
    else break;
  }
  // Split into export statements (statements may span lines).
  const statements = [];
  const re = /^export /gm;
  const starts = [];
  let m;
  while ((m = re.exec(text)) !== null) starts.push(m.index);
  for (let i = 0; i < starts.length; i++) {
    const end = i + 1 < starts.length ? starts[i + 1] : text.length;
    statements.push(text.slice(starts[i], end).trim());
  }

  const numbers = [];
  const byteArrays = [];
  const strings = [];
  const frozen = [];
  const functions = [];
  const unrendered = [];

  for (const stmt of statements) {
    let mm;
    if (
      (mm = stmt.match(/^export const ([A-Za-z0-9_]+) = (-?\d+) as const;$/))
    ) {
      numbers.push({ name: mm[1], value: Number(mm[2]) });
    } else if (
      (mm = stmt.match(
        /^export const ([A-Za-z0-9_]+) = Uint8Array\.from\(\[([\s\S]*?)\]\);$/,
      ))
    ) {
      const bytes = mm[2]
        .split(",")
        .map((s) => s.trim())
        .filter((s) => s.length > 0)
        .map((s) => Number(s));
      byteArrays.push({ name: mm[1], bytes });
    } else if (
      (mm = stmt.match(
        /^export const ([A-Za-z0-9_]+) = new TextEncoder\(\)\.encode\('([^']*)'\);$/,
      ))
    ) {
      strings.push({ name: mm[1], value: mm[2] });
    } else if (
      (mm = stmt.match(
        /^export const ([A-Za-z0-9_]+) = '([^']*)' as const;$/,
      ))
    ) {
      strings.push({ name: mm[1], value: mm[2] });
    } else if (
      (mm = stmt.match(
        /^export const ([A-Za-z0-9_]+) = Object\.freeze\(([\s\S]*?)\) as [\s\S]*?;$/,
      ))
    ) {
      let value = null;
      try {
        value = JSON.parse(mm[2]);
      } catch {
        unrendered.push(stmt);
        continue;
      }
      frozen.push({ name: mm[1], value });
    } else if ((mm = stmt.match(/^export function ([A-Za-z0-9_]+)/))) {
      functions.push({ name: mm[1] });
    } else {
      unrendered.push(stmt);
    }
  }

  return {
    file: name,
    header: headerLines,
    numbers,
    byteArrays,
    strings,
    frozen,
    functions,
    unrendered,
  };
}

