// ---- routes.md

{
  const sections = [];
  const neverExecuted = [];
  for (const p of programs) {
    const routes = [...p.routes].sort((a, b) => (a.id < b.id ? -1 : 1));
    const rows = routes.map((r) => {
      const sel = r.selectors
        .map((s) => {
          if (s.kind === "magic") {
            const bytes = [];
            for (let i = 0; i < s.bytes.length; i += 2) {
              bytes.push(parseInt(s.bytes.slice(i, i + 2), 16));
            }
            const a = s.ascii ?? asciiBytes(bytes);
            return a ? `magic \`${a}\`` : `magic \`${s.bytes}\``;
          }
          if (s.kind === "variant") return `variant \`${s.path}\``;
          return `${s.kind} \`${s.constant ?? s.path ?? ""}\``;
        })
        .join("; ");
      const st = routeStatus(r.id);
      if (st.kind === "none") neverExecuted.push(r.id);
      return [
        `\`${r.id}\``,
        r.kind,
        sel || "--",
        st.text,
        `\`${r.provenance}\``,
      ];
    });
    sections.push(
      `## ${p.label}\n\n` +
        table(["route", "kind", "selector", "status", "provenance"], rows),
    );
  }

  let unknown = "";
  if (unknownRefs.length > 0) {
    const rows = unknownRefs
      .sort((a, b) => (a.ref < b.ref ? -1 : 1))
      .map((u) => [`\`${u.ref}\``, `\`${u.file}\``, u.label]);
    unknown =
      `\n\n## Campaign records naming routes the code does not\n\n` +
      `These route names appear in a campaign's records but match no route in
the current code. Each one is stale or a gap; it is listed here so it gets
fixed rather than dropped.\n\n` +
      table(["reference", "bindings file", "binding label"], rows);
  }

  pages.set(
    "routes.md",
    generatedHeader([
      "census inventory",
      "tools/gauntlet/blocked.json",
      "tools/gauntlet/*/bindings",
    ]) +
      `# Routes

Every instruction the programs accept, with its selector and where it
stands:

- **witnessed** -- an in-tree test campaign has actually run this route
  (that is test coverage, not a proof about every input). The campaign is
  named in the row.
- **blocked** -- the route cannot be driven yet, and the reason is written
  down in \`tools/gauntlet/blocked.json\` (rows show the first sentence;
  the file has the rest).
- **NEVER-EXECUTED** -- no campaign has run it and no reason is recorded
  yet.

Currently **${neverExecuted.length}** of **${inventoryRouteIds.size}**
routes are in that last group.

` +
      sections.join("\n\n") +
      unknown +
      "\n",
  );
}

