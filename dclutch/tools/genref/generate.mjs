function walk(dir, base = dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir).sort()) {
    const p = path.join(dir, e);
    if (fs.statSync(p).isDirectory()) walk(p, base, acc);
    else acc.push(path.relative(base, p));
  }
  return acc;
}

const expected = new Map(
  [...pages.entries()].sort(([a], [b]) => (a < b ? -1 : 1)),
);

if (check) {
  const existing = walk(OUT_DIR);
  let failed = false;
  for (const [rel, content] of expected) {
    const p = path.join(OUT_DIR, rel);
    if (!fs.existsSync(p)) {
      console.error(`genref check: MISSING ${path.relative(REPO, p)}`);
      failed = true;
    } else if (read(p) !== content) {
      console.error(`genref check: STALE ${path.relative(REPO, p)}`);
      failed = true;
    }
  }
  for (const rel of existing) {
    if (!expected.has(rel)) {
      console.error(
        `genref check: STRAY ${path.join("docs/reference", rel)} (not produced by the generator)`,
      );
      failed = true;
    }
  }
  if (failed) {
    console.error(
      "genref check: docs/reference is not the generator's output. Regenerate with tools/genref/generate.sh and commit the result.",
    );
    process.exit(1);
  }
  console.log(
    `genref check: docs/reference matches (${expected.size} files, byte-identical).`,
  );
} else {
  fs.mkdirSync(path.join(OUT_DIR, "abi"), { recursive: true });
  for (const [rel, content] of expected) {
    const p = path.join(OUT_DIR, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    const tmp = p + ".genref-tmp";
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, p);
  }
  for (const rel of walk(OUT_DIR)) {
    if (!expected.has(rel)) {
      fs.unlinkSync(path.join(OUT_DIR, rel));
      console.log(`genref: removed stray ${path.join("docs/reference", rel)}`);
    }
  }
  console.log(`genref: wrote ${expected.size} files under docs/reference/.`);
}
