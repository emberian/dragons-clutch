// ---- routes.md

// A route's admissible Market prestates, as the guard's own named constant
// declares them. The census reads the constant structurally; this renders it.
// An empty list is NOT "every phase" -- it is "no phase gate was read here" --
// and the two must not print the same, because a client that cannot tell them
// apart is the defect this column exists to close.
function phaseGate(route, program) {
  const gates = route.admissible_prestates ?? [];
  // "no constant was read here" and "there is no discriminant to read" are
  // different facts about a route, and a client that cannot tell them apart
  // keeps waiting for a phase answer that will never arrive. The census
  // declares the second per program, with its own staleness checks.
  if (gates.length === 0) {
    return program?.no_persisted_discriminant
      ? "no state machine"
      : "no phase gate";
  }
  // Every set NAMES ITS MACHINE. The whole content of a declaration is which
  // discriminant it constrains, and a Market is `Open` for the entire span in
  // which its Source moves `Primary` to `Resolved` -- so a cell that dropped
  // the machine would invite a reader to check a Source set against a Market
  // phase and publish an admission nobody declared.
  const render = (g) => {
    const body =
      g.prestates && g.prestates.length > 0
        ? g.prestates.map((s) => `${s.phase}+${s.readiness}`).join(", ")
        : g.phases.join(", ");
    return `\`${g.machine ?? "market"}: ${body}\``;
  };
  // Entries sharing an `alternative` are the branches of ONE selection, so
  // they unite; everything else is a separate gate on the same execution, so
  // it intersects. Printing them the same way makes a route that admits three
  // phases read as a route that admits none.
  const groups = new Map();
  const conjuncts = [];
  for (const gate of gates) {
    if (gate.alternative === undefined || gate.alternative === null) {
      conjuncts.push(render(gate));
      continue;
    }
    if (!groups.has(gate.alternative)) groups.set(gate.alternative, []);
    groups.get(gate.alternative).push(render(gate));
  }
  for (const members of groups.values()) {
    conjuncts.push(members.length === 1 ? members[0] : members.join(" or "));
  }
  return conjuncts.join("; ");
}

