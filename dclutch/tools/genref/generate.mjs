#!/usr/bin/env node
// tools/genref/generate.mjs -- emits docs/reference/ from the protocol's own
// authorities. The OUTPUTS are generated; this file is the hand-written
// renderer and carries the reference's connective prose as templates.
//
// Sources (all in-tree except the inventory, which is produced fresh from the
// tree by the census tool each run):
//   - the route/refusal inventory emitted by `dclutch-route-census inventory`
//     (tools/gauntlet/census), passed in with --inventory
//   - tools/gauntlet/blocked.json
//   - tools/gauntlet/*/bindings.json and */*-bindings.json
//   - tools/gauntlet/CU_BUDGETS.json
//   - crates/dclutch-refusal-registry/src/lib.rs (band allocation)
//   - docs/decisions/*.md (ADR index)
//   - apps/dclutch-web/lib/generated/*.ts (the Lean/Rust-emitted ABI modules,
//     each byte-gated by its own `abi:*:verify`)
//
// Modes:
//   node generate.mjs --inventory FILE            regenerate docs/reference/
//   node generate.mjs --inventory FILE --check    byte-compare, write nothing
//
// docs/reference/ is wholly owned by this generator: on regenerate, stray
// files there are removed; on --check, they fail the gate. Every write goes
// through a same-directory temporary file and an atomic rename, so a failed
// run leaves the last accepted output byte-for-byte intact (AGENTS.md,
// "never redirect a generator directly into a canonical tracked output").
//
// Determinism: no timestamps, no absolute paths, every collection sorted.
// The check gate is the proof.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");

// ---------------------------------------------------------------- arguments

const argv = process.argv.slice(2);
let inventoryPath = null;
let check = false;
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "--inventory") inventoryPath = argv[++i];
  else if (argv[i] === "--check") check = true;
  else {
    console.error(`genref: unknown argument ${argv[i]}`);
    process.exit(2);
  }
}
if (!inventoryPath) {
  console.error(
    "genref: --inventory FILE is required (tools/genref/generate.sh produces it)",
  );
  process.exit(2);
}

const OUT_DIR = path.join(REPO, "docs", "reference");

// ------------------------------------------------------------------ helpers

const readJSON = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const read = (p) => fs.readFileSync(p, "utf8");

function mdCell(s) {
  return String(s).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function table(headers, rows, align = null) {
  const sep = headers.map((_, i) =>
    align && align[i] === "r" ? "---:" : "---",
  );
  const line = (cells) => `| ${cells.map(mdCell).join(" | ")} |`;
  return [line(headers), `| ${sep.join(" | ")} |`, ...rows.map(line)].join(
    "\n",
  );
}

function hexBytes(bytes) {
  return bytes.map((b) => b.toString(16).padStart(2, "0")).join(" ");
}

function asciiBytes(bytes) {
  if (bytes.every((b) => b >= 0x20 && b <= 0x7e)) {
    return bytes.map((b) => String.fromCharCode(b)).join("");
  }
  return "";
}

function codeHex(code) {
  return "0x" + code.toString(16).toUpperCase().padStart(4, "0");
}

function num(n) {
  return n.toLocaleString("en-US");
}

function generatedHeader(sources) {
  return [
    "<!--",
    "  @generated by tools/genref/generate.mjs -- DO NOT EDIT.",
    "  Regenerate: tools/genref/generate.sh",
    "  Verify:     tools/genref/generate.sh --check",
    `  Sources: ${sources.join("; ")}`,
    "-->",
    "",
  ].join("\n");
}

