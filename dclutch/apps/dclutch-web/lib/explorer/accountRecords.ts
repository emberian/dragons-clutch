// ------------------------------------------------------------------ the shape

/**
 * How a field's bytes are read.
 *
 * `pubkey` and `identity` are both exactly 32 bytes and differ only in how they
 * are shown: a `pubkey` is an account this explorer can navigate to; an
 * `identity` is a content digest that names a record body, not an address.
 * `identity32` is the honest middle: 32 bytes whose emitted name does not settle
 * which, shown as both.
 */
export type RecordFieldKind =
  | 'u8'
  | 'u16'
  | 'u32'
  | 'u64'
  /**
   * A signed 64-bit integer. The window record's two bounds are the first
   * signed scalars any dClutch account publishes -- unix seconds, which Rust
   * writes as `i64` -- and reading them as `u64` would render a pre-1970
   * instant as eighteen quintillion rather than as a negative second.
   */
  | 'i64'
  /**
   * A signed 128-bit integer. `StatisticSpecV1.threshold_atoms` is the only one
   * the protocol publishes -- a signed atom count wide enough that reading it as
   * two `u64`s would show a reader two numbers neither of which is the value.
   */
  | 'i128'
  /**
   * `StatisticSpecV1.source_scale_exponent`: a signed 32-bit decimal shift that
   * carries its own reading.
   *
   * It is not `i32` with a note, because a note is written once and the reading
   * changes with the value. `0` and `-8` are the same field and different
   * sentences: the first says the observation and the cuts are compared as
   * written, the second says the observation is eight decimal places finer than
   * the cuts it is compared against. A reader shown `-8` and left to work out
   * which side moves is being shown the byte, not the fact.
   */
  | 'scale-exponent'
  | 'pubkey'
  | 'identity'
  | 'identity32'
  | 'enum'
  | 'reserved'
  | 'span';

export type EnumTag = Readonly<{ tag: number; name: string }>;

export type RecordField = Readonly<{
  label: string;
  offset: number;
  kind: RecordFieldKind;
  /** Named tags, for `enum` fields. A byte outside them renders as unnamed. */
  tags?: ReadonlyArray<EnumTag>;
  /** What the span holds, for `span` fields. */
  note?: string;
}>;

/**
 * How many rows follow a class header.
 *
 * `u32-at` reads a count the wire sends. `fixed` is a count the ACTION already
 * determines, which the wire therefore stopped sending -- the explorer derives
 * it exactly as the program does rather than reading a field that is not there.
 */
export type RecordRowCount =
  | Readonly<{ kind: 'fixed'; count: number }>
  | Readonly<{ kind: 'u32-at'; offset: number }>;

/** One action class of a record whose header depends on its action byte. */
export type RecordActionClass = Readonly<{
  /** What this class is called where the reader can see it. */
  name: string;
  /** The action bytes that select it. */
  actions: ReadonlyArray<number>;
  headerBytes: number;
  strideBytes: number;
  rowLabel: string;
  rows: RecordRowCount;
  /** What this class carries BEYOND the common prefix in `RecordSpec.fields`. */
  fields: ReadonlyArray<RecordField>;
}>;

/** How wide the record is, and how that width is known. */
export type RecordWidth =
  | Readonly<{ kind: 'fixed'; bytes: number }>
  | Readonly<{
      kind: 'header-and-rows';
      headerBytes: number;
      strideBytes: number;
      countOffset: number;
      countKind: 'u8' | 'u16' | 'u32';
      rowLabel: string;
    }>
  /**
   * A record whose header layout depends on its own action byte.
   *
   * The Rational representation request became this in physical ABI v3: one
   * common prefix placed identically for every action, then a tail that differs
   * by class. Reading it with a single flat field list -- which is what this
   * file did -- produced a plausible number for every field past the prefix no
   * matter which action was on the wire, because every offset still landed
   * inside the account. Nothing was out of range, so nothing looked wrong.
   */
  | Readonly<{
      kind: 'action-classes';
      /** Where the selecting action byte lives. In the common prefix, always. */
      actionOffset: number;
      /** Where the common prefix ends, which is where `span` fields stop. */
      commonPrefixBytes: number;
      classes: ReadonlyArray<RecordActionClass>;
    }>
  | Readonly<{ kind: 'header-only'; headerBytes: number; note: string }>;

export type RecordSpec = Readonly<{
  /** The magic, exactly as the generated module exports it. */
  magic: string | Uint8Array;
  name: string;
  /** The program family that writes or reads it. */
  family: string;
  summary: string;
  width: RecordWidth;
  fields: ReadonlyArray<RecordField>;
  /**
   * A discriminant that lives in every ROW rather than in the header.
   *
   * The funding ledger is the only record that has one, and a flat field
   * cannot reach it: offset zero of a slot is offset 48, 120, 192 … of the
   * account, so declaring it in `fields` would read the magic and call the
   * answer a state. It is declared here instead and decoded once per row.
   */
  rowDiscriminant?: Readonly<{
    label: string;
    /** Where the tag sits INSIDE one row, not inside the account. */
    offset: number;
    strideBytes: number;
    tags: ReadonlyArray<EnumTag>;
  }>;
  /**
   * Why the field list is empty or partial, when it is. A record whose module
   * emitted no offsets is still identified — it just says so here rather than
   * showing fields nobody emitted.
   */
  note: string | null;
}>;

