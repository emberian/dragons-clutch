/**
 * `SourceResolutionStateV2`'s byte coordinates, for the clients that read one.
 *
 * The Source record already arrives in the browser once, through
 * `stateMachinesV1.ts`, which carries its magic, its width, its pinned header
 * words and its phase tags — everything a reader needs to say WHICH state a
 * Source is in. What that table does not carry is where the record's FIELDS
 * live, because it is emitted from each machine's discriminant decoder rather
 * than from the record's layout.
 *
 * So a card that wants to print a Source's market, generation, active attempt,
 * terminal route, selector or terminal sequence had exactly two options: state
 * the offsets itself, or drop the fields. `lib/localSuccessor.ts` did the
 * first and then, in 3d41f8f85, the second — six fields left the card rather
 * than stay as literals with no owner. This module is the third option, and
 * the only one that is not a hand-mirror: the same coordinates, read from the
 * Lean-emitted Rust that owns them.
 *
 * Source: `crates/dclutch-source/src/generated_source_resolution_state_v2.rs`,
 * itself `@generated by formal/dclutch-semantics/EmitSourceResolutionStateV2AbiRust.lean`.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const sourcePath = new URL('crates/dclutch-source/src/generated_source_resolution_state_v2.rs', root);
const source = readFileSync(sourcePath, 'utf8');
const outputUrl = new URL('../lib/generated/sourceResolutionStateV2.ts', import.meta.url);

function scalar(name) {
  const match = source.match(new RegExp(`pub(?:\\(crate\\))? const ${name}: (?:usize|u8|u16|u32|u64) = ([0-9_]+);`));
  if (!match) throw new Error(`missing Rust scalar ${name}`);
  return match[1].replaceAll('_', '');
}

function fixedBytes(name) {
  const match = source.match(new RegExp(`const ${name}: \\[u8; ([0-9]+)\\] = \\[([\\s\\S]*?)\\n\\];`));
  if (!match) throw new Error(`missing Rust byte array ${name}`);
  const bytes = [...match[2].matchAll(/0x([0-9a-f]{2})/g)].map((entry) => Number.parseInt(entry[1], 16));
  if (bytes.length !== Number(match[1])) throw new Error(`${name} has ${bytes.length} bytes, expected ${match[1]}`);
  return bytes;
}

function hex(bytes) { return bytes.map((byte) => byte.toString(16).padStart(2, '0')).join(''); }

function ascii(bytes) {
  if (bytes.some((byte) => byte < 0x20 || byte > 0x7e)) throw new Error('Source resolution state magic is not printable ASCII');
  return String.fromCharCode(...bytes);
}

/**
 * Every offset the Rust module declares, in the order it declares them.
 *
 * Scraped rather than listed, so a coordinate added to the Lean schema arrives
 * here by regeneration instead of by somebody remembering to add a name — and
 * so this script cannot silently emit a SUBSET of the record's layout, which
 * is the shape a hand-kept list drifts into.
 */
const offsetNames = [...source.matchAll(/pub const (SOURCE_RESOLUTION_STATE_V2_[A-Z0-9_]*_OFFSET): usize = [0-9_]+;/g)]
  .map((match) => match[1]);
if (offsetNames.length < 8) throw new Error(`only ${offsetNames.length} Source resolution state offsets found; the scrape is wrong`);

const magic = fixedBytes('SOURCE_RESOLUTION_STATE_V2_MAGIC');
const lines = [
  '// @generated by scripts/generate-source-resolution-state-v2.mjs; do not edit.',
  '// Source: crates/dclutch-source/src/generated_source_resolution_state_v2.rs, itself Lean-emitted.',
  '//',
  '// The magic and the phase tags also arrive through stateMachinesV1.ts, which is',
  '// emitted from the machine\'s own Rust decoder. This module is the FIELD map that',
  '// table does not carry, and it exists so a client can name a Source\'s market,',
  '// generation, attempt, route, selector and terminal sequence without writing a',
  '// byte coordinate of its own.',
  '',
  `export const SOURCE_RESOLUTION_STATE_V2_MAGIC = '${ascii(magic)}' as const;`,
  `export const SOURCE_RESOLUTION_STATE_V2_BYTES = ${scalar('SOURCE_RESOLUTION_STATE_V2_BYTES')} as const;`,
  `export const SOURCE_RESOLUTION_STATE_V2_SCHEMA_VERSION = ${scalar('SOURCE_RESOLUTION_STATE_V2_SCHEMA_VERSION')} as const;`,
  '',
  ...offsetNames.map((name) => `export const ${name} = ${scalar(name)} as const;`),
  '',
  '/** Canonical Rust fixtures: one Source that has not resolved, one wide terminal. */',
  `export const SOURCE_RESOLUTION_STATE_V2_FRESH_EXAMPLE_HEX = '${hex(fixedBytes('SOURCE_RESOLUTION_STATE_V2_FRESH_EXAMPLE'))}' as const;`,
  `export const SOURCE_RESOLUTION_STATE_V2_WIDE_TERMINAL_EXAMPLE_HEX = '${hex(fixedBytes('SOURCE_RESOLUTION_STATE_V2_WIDE_TERMINAL_EXAMPLE'))}' as const;`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== lines) {
    process.stderr.write('lib/generated/sourceResolutionStateV2.ts is stale; run npm run abi:source-resolution-state-v2\n');
    process.exit(1);
  }
  process.stdout.write('lib/generated/sourceResolutionStateV2.ts matches its Lean-emitted Rust source\n');
} else {
  writeFileSync(outputUrl, lines);
  process.stdout.write('wrote lib/generated/sourceResolutionStateV2.ts\n');
}
