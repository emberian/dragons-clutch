output += '\n';
output += `export const CUSTODY_VAULT_PDA_DOMAIN_V1 = new TextEncoder().encode('${byteString('custody', 'CUSTODY_VAULT_PDA_DOMAIN_V1')}');\n`;
output += `export const CUSTODY_AUTHORITY_PDA_DOMAIN_V1 = new TextEncoder().encode('${byteString('custody', 'CUSTODY_AUTHORITY_PDA_DOMAIN_V1')}');\n`;
output += `export const CUSTODY_COMPARTMENT_HOARD_PRINCIPAL_TAG_V1 = ${scalar('custody', 'CUSTODY_COMPARTMENT_HOARD_PRINCIPAL_TAG_V1')} as const;\n`;

// -------------------------------------------------------- the Realm record
// The Realm body layout used to be re-emitted here from the crate's literals.
// It is now Lean-emitted directly into lib/generated/realmPositionV1.ts by
// `npm run abi:realm-position`; a Realm coordinate stated in two generated
// modules would be exactly the drift this pipeline exists to remove.

const owned = [...constantReads].filter((key) =>
  emittedSources.has(key.slice(0, key.indexOf('.'))),
).length;
const total = constantReads.size;
console.log(
  `coreFound: ${owned} of ${total} constant reads Lean-owned, ` +
    `from ${emittedSources.size} of ${Object.keys(sources).length} sources emitted`,
);
if (process.argv.includes('--unowned')) {
  // The remaining work, as a worklist rather than a paragraph: every constant
  // this browser module still takes from a file a human maintains, grouped by
  // the crate that would need a Lean owner to retire it.
  const bySource = new Map();
  for (const key of [...constantReads].sort()) {
    const source = key.slice(0, key.indexOf('.'));
    if (emittedSources.has(source)) continue;
    if (!bySource.has(source)) bySource.set(source, []);
    bySource.get(source).push(key.slice(key.indexOf('.') + 1));
  }
  for (const [source, names] of [...bySource].sort()) {
    console.log(`  ${source} (${names.length}): ${names.join(', ')}`);
  }
}

if (process.argv.includes('--check')) {
  if (owned < OWNED_FLOOR) {
    console.error(
      `Core Found Lean ownership REGRESSED: ${owned} < ${OWNED_FLOOR}. ` +
        'Raising this floor is how the ratchet advances; lowering it needs a reason.',
    );
    process.exit(1);
  }
  if (readFileSync(outputUrl, 'utf8') !== output) {
    console.error('Core Found TypeScript ABI is stale');
    process.exit(1);
  }
} else {
  writeFileSync(fileURLToPath(outputUrl), output);
}
