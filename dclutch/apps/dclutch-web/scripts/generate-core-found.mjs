// --------------------------------------------------- how much of this is Lean's
//
// "coreFound is 82 of 95 Lean-owned" was a number that existed ONLY in commit
// messages. Nothing computed it, so nothing could contradict a wrong one, and a
// conversion that silently regressed it would read exactly like one that did
// not. That is the same gap `tools/emission-guard/COVERAGE.md` exists to close,
// and the same answer: derive the number, print it on every run, and gate it
// against a floor that moves only when somebody edits one line on purpose.
//
// A source is Lean-owned when its FIRST LINE is an emitter provenance header.
// That is the whole test, and it is the right one: a file whose header names
// `formal/dclutch-semantics/Emit*.lean` has a byte-compare guard behind it in
// the emission census, and a file without one is a file some human is typing.
//
// What this counts is CONSTANT reads -- every `scalar`/`bytes`/`byteString`/
// `stringConstant` lookup, deduplicated by source and name. It does NOT count
// the two table scrapes (the account-role table and the operator's key order),
// because those are regexes over a file's structure rather than reads of a
// named constant, and folding them in would make the denominator mean two
// different things at once. So this number is not the previous lane's hand
// count and should not be expected to match it; it is a number with an
// instrument, which the hand count never was.
