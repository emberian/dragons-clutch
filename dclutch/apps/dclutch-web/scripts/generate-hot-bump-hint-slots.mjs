// Generate lib/generated/hotBumpHintSlotsV1.ts from the Rust authorities.
//
// The hot envelope's caller-mined bump-hint block has three facts a client
// must not restate: where the block sits in the envelope, how many slots it
// has, and what each slot NAMES. The first two belong to the envelope
// (dclutch-market); the third belongs to the block's one
// host-side producer (dclutch-hot-bump-miner-v1), which is where
// `HOT_BUMP_HINT_SLOT_NAMES_V1` lives.
//
// All three used to be hand-authored in `lib/directHotBumpHintsV1.ts`, in both
// twins, and the names had already DRIFTED from the Rust: the browser glossed
// the family-neutral slots with Direct account names ("lifecycle 0 (seller
// maker replay)") on a block whose own doc comment says the slots are roles in
// any hot execution and never Direct accounts. A cross-family reader shown that
// name is being told something false about the route it is looking at.
//
// Every name here is therefore the producer's, read from the producer, and
// `--check` is what keeps it that way.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../../', import.meta.url);
const sources = Object.freeze({
  envelope: readFileSync(new URL('crates/dclutch-market/src/capability_program/hot_v3.rs', root), 'utf8'),
  miner: readFileSync(new URL('crates/dclutch-hot-bump-miner-v1/src/lib.rs', root), 'utf8'),
});
const outputUrl = new URL('../lib/generated/hotBumpHintSlotsV1.ts', import.meta.url);

function scalar(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub(?:\\(crate\\))? )?const ${name}: [^=]+ = ([0-9]+);`));
  if (!match) throw new Error(`missing Rust scalar ${source}.${name}`);
  return Number(match[1]);
}

/**
 * The producer's slot-name table, in declaration order.
 *
 * Refuses anything but a plain list of double-quoted ASCII names, so a Rust
 * side that grew an expression, a `concat!`, or a non-ASCII name is a loud
 * failure here rather than a silently truncated TypeScript array.
 */
function slotNames() {
  const body = sources.miner.match(/pub const HOT_BUMP_HINT_SLOT_NAMES_V1: \[&str; [A-Z_0-9]+\] = \[([\s\S]*?)\n\];/);
  if (!body) throw new Error('missing Rust HOT_BUMP_HINT_SLOT_NAMES_V1');
  const names = [];
  for (const line of body[1].split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '') continue;
    const match = trimmed.match(/^"([\x20-\x7e]*)",$/);
    if (!match) throw new Error(`HOT_BUMP_HINT_SLOT_NAMES_V1 entry is not a plain ASCII string literal: ${trimmed}`);
    if (match[1].includes("'") || match[1].includes('\\')) throw new Error(`slot name needs escaping: ${match[1]}`);
    names.push(match[1]);
  }
  return names;
}

const count = scalar('envelope', 'HOT_BUMP_HINT_COUNT_V1');
const offset = scalar('envelope', 'HOT_BUMP_HINTS_OFFSET_V1');
const names = slotNames();
if (names.length !== count) {
  throw new Error(`HOT_BUMP_HINT_SLOT_NAMES_V1 has ${names.length} names for ${count} slots`);
}

let output = '// @generated by scripts/generate-hot-bump-hint-slots.mjs; do not edit.\n';
output += '// Authorities: dclutch-market/src/hot_v3.rs (offset, count),\n';
output += '// dclutch-hot-bump-miner-v1/src/lib.rs (slot names).\n\n';
output += '/** Byte offset of the caller-mined bump-hint block inside the hot envelope. */\n';
output += `export const HOT_BUMP_HINTS_OFFSET_V1 = ${offset} as const;\n\n`;
output += '/** Number of bump-hint slots in the hot envelope. */\n';
output += `export const HOT_BUMP_HINT_COUNT_V1 = ${count} as const;\n\n`;
output += '/**\n';
output += ' * What each slot names, in canonical wire order.\n';
output += ' *\n';
output += ' * The slots are ROLES in any hot execution, never one family\'s accounts:\n';
output += ' * the envelope is family-neutral. A failure that names a slot names it from\n';
output += ' * here, in the producer\'s own words.\n';
output += ' */\n';
output += 'export const HOT_BUMP_HINT_SLOT_NAMES_V1 = Object.freeze([\n';
for (const name of names) output += `  '${name}',\n`;
output += '] as const);\n\n';
output += '/**\n';
output += ' * Name the hint slot a HOT ENVELOPE offset lands in, if it lands in one.\n';
output += ' *\n';
output += ' * `undefined` for every offset outside the block, so a caller may ask this of\n';
output += ' * any offset in a hot instruction and get an answer only where there is one.\n';
output += ' */\n';
output += 'export function hotBumpHintSlotNameV1(envelopeOffset: number): string | undefined {\n';
output += '  const slot = envelopeOffset - HOT_BUMP_HINTS_OFFSET_V1;\n';
output += '  if (!Number.isInteger(slot) || slot < 0 || slot >= HOT_BUMP_HINT_COUNT_V1) return undefined;\n';
output += '  return HOT_BUMP_HINT_SLOT_NAMES_V1[slot];\n';
output += '}\n';

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== output) {
    console.error('hot bump hint slot TypeScript ABI is stale');
    process.exit(1);
  }
} else {
  writeFileSync(fileURLToPath(outputUrl), output);
}
