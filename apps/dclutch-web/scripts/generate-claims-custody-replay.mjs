// Generate lib/generated/claimsCustodyReplayV1.ts from the Rust authorities.
//
// The Claims-role Custody replay is the cursor a redemption replays against,
// and creating it is the ONE wallet-constructible instruction ahead of every
// payout: ADR-0008 §7.3 obliges "any redemption builder, including the
// browser's" to open with replay creation when the Claims-role replay is
// absent. This module carries everything a browser builder needs to author
// that instruction without restating a single Rust literal:
//
//   - the 48-byte `DCLCCR01` request wire (dclutch-claims-svm);
//   - the 14-account frame in the adapter's own coordinate order
//     (programs/dclutch-claims-sbf);
//   - the 672-byte Custody `DCLCUSR1` request the route derives, whose SHA-256
//     seeds the Claims caller-authority PDA (dclutch-custody-contract's
//     Lean-emitted offsets);
//   - the replay account layout and the PDA seed domains/roles
//     (dclutch-custody-contract, dclutch-release-set-contract).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../../', import.meta.url);
const sources = Object.freeze({
  claimsWire: readFileSync(new URL('crates/dclutch-claims-svm/src/custody_replay_v1.rs', root), 'utf8'),
  claimsRoute: readFileSync(new URL('programs/dclutch-claims-sbf/src/custody_replay_v1.rs', root), 'utf8'),
  custodyGenerated: readFileSync(new URL('crates/dclutch-custody-contract/src/generated.rs', root), 'utf8'),
  custodyLib: readFileSync(new URL('crates/dclutch-custody-contract/src/lib.rs', root), 'utf8'),
  custodyFrame: readFileSync(new URL('crates/dclutch-custody-contract/src/frame_spec_v1.rs', root), 'utf8'),
  releaseSet: readFileSync(new URL('crates/dclutch-release-set-contract/src/lib.rs', root), 'utf8'),
  registryActivation: readFileSync(new URL('crates/dclutch-registry-contract/src/activation.rs', root), 'utf8'),
});
const outputUrl = new URL('../lib/generated/claimsCustodyReplayV1.ts', import.meta.url);

function scalar(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub(?:\\(crate\\))? )?const ${name}: [^=]+ = ([0-9]+);`));
  if (!match) throw new Error(`missing Rust scalar ${source}.${name}`);
  return Number(match[1]);
}

function magic(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub )?const ${name}: \\[u8; 8\\] = \\*b"([^"]+)";`));
  if (!match) throw new Error(`missing Rust magic ${source}.${name}`);
  return match[1];
}

function byteString(source, name) {
  const match = sources[source].match(new RegExp(`(?:pub )?const ${name}: &\\[u8(?:; [0-9]+)?\\] =\\s*b"([^"]+)";`));
  if (!match) throw new Error(`missing Rust byte string ${source}.${name}`);
  return match[1];
}

function discriminant(source, enumeration, variant) {
  const body = sources[source].match(new RegExp(`pub enum ${enumeration} \\{([\\s\\S]*?)\\n\\}`));
  if (!body) throw new Error(`missing Rust enumeration ${source}.${enumeration}`);
  const match = body[1].match(new RegExp(`\\n\\s*${variant} = ([0-9]+),`));
  if (!match) throw new Error(`missing Rust ${enumeration}::${variant} discriminant`);
  return Number(match[1]);
}

let output = '// @generated by scripts/generate-claims-custody-replay.mjs; do not edit.\n';
output += '// Authorities: dclutch-claims-svm/src/custody_replay_v1.rs,\n';
output += '// programs/dclutch-claims-sbf/src/custody_replay_v1.rs,\n';
output += '// dclutch-custody-contract/src/{generated.rs,lib.rs,frame_spec_v1.rs},\n';
output += '// dclutch-release-set-contract/src/lib.rs.\n\n';

// ----------------------------------------------------- the 48-byte request
output += `export const CLAIMS_CUSTODY_REPLAY_REQUEST_MAGIC_V1 = new TextEncoder().encode('${magic('claimsWire', 'CLAIMS_CUSTODY_REPLAY_REQUEST_MAGIC_V1')}');\n`;
for (const name of ['CLAIMS_CUSTODY_REPLAY_REQUEST_BYTES_V1', 'CLAIMS_CUSTODY_REPLAY_VERSION_V1']) {
  output += `export const ${name} = ${scalar('claimsWire', name)} as const;\n`;
}
for (const [exported, rust] of [
  ['CLAIMS_CUSTODY_REPLAY_VERSION_OFFSET_V1', 'VERSION_OFFSET'],
  ['CLAIMS_CUSTODY_REPLAY_RESERVED_OFFSET_V1', 'RESERVED_OFFSET'],
  ['CLAIMS_CUSTODY_REPLAY_RESERVED_BYTES_V1', 'RESERVED_BYTES'],
  ['CLAIMS_CUSTODY_REPLAY_MARKET_OFFSET_V1', 'MARKET_OFFSET'],
]) output += `export const ${exported} = ${scalar('claimsWire', rust)} as const;\n`;

// -------------------------------------------- the route's 14-account frame
output += '\n';
output += `export const CLAIMS_CUSTODY_REPLAY_PARENT_DOMAIN_V1 = new TextEncoder().encode('${byteString('claimsRoute', 'CLAIMS_CUSTODY_REPLAY_PARENT_DOMAIN_V1')}');\n`;
output += `export const CLAIMS_CUSTODY_REPLAY_ACCOUNT_COUNT_V1 = ${scalar('claimsRoute', 'CLAIMS_CUSTODY_REPLAY_ACCOUNT_COUNT_V1')} as const;\n`;
for (const name of [
  'CUSTODY_CALLER_AUTHORITY', 'CORE_MARKET', 'ACTIVATION_CACHE', 'REGISTRY_PROGRAM', 'CLAIMS_PROGRAM',
  'CLAIMS_PROGRAMDATA', 'REALM', 'REALM_STAGING', 'CUSTODY_REPLAY', 'PAYER', 'SYSTEM_PROGRAM',
  'RENT_SYSVAR', 'CUSTODY_PROGRAM', 'AGGREGATE',
]) output += `export const REPLAY_ACCOUNT_${name}_V1 = ${scalar('claimsRoute', name)} as const;\n`;
output += `export const CUSTODY_INITIALIZE_REPLAY_ACCOUNT_COUNT_V1 = ${scalar('custodyFrame', 'INITIALIZE_REPLAY_ACCOUNT_COUNT_V1')} as const;\n`;

// ------------------------------------ the Custody request the route derives
output += '\n';
output += `export const CUSTODY_REQUEST_MAGIC_V1 = new TextEncoder().encode('${magic('custodyLib', 'CUSTODY_REQUEST_MAGIC_V1')}');\n`;
output += `export const CUSTODY_REPLAY_MAGIC_V1 = new TextEncoder().encode('${magic('custodyLib', 'CUSTODY_REPLAY_MAGIC_V1')}');\n`;
for (const name of ['CUSTODY_REQUEST_BYTES_V1', 'CUSTODY_REPLAY_BYTES_V1', 'ABI_VERSION_V1']) {
  output += `export const CUSTODY_${name === 'ABI_VERSION_V1' ? 'ABI_VERSION_V1' : name.replace('CUSTODY_', '')} = ${scalar('custodyGenerated', name)} as const;\n`;
}
for (const name of [
  'REQUEST_VERSION_OFFSET', 'REQUEST_OPERATION_OFFSET', 'REQUEST_CALLER_ROLE_OFFSET',
  'REQUEST_SOURCE_COMPARTMENT_OFFSET', 'REQUEST_DESTINATION_COMPARTMENT_OFFSET', 'REQUEST_TRANSFER_INDEX_OFFSET',
  'REQUEST_RELEASE_SET_OFFSET', 'REQUEST_MARKET_OFFSET', 'REQUEST_REALM_OFFSET', 'REQUEST_CONTEXT_OFFSET',
  'REQUEST_CALLER_PROGRAM_OFFSET', 'REQUEST_CANDIDATE_OFFSET', 'REQUEST_SOURCE_OWNER_OFFSET',
  'REQUEST_DESTINATION_OWNER_OFFSET', 'REQUEST_ORDER_OFFSET', 'REQUEST_PARENT_REQUEST_DIGEST_OFFSET',
  'REQUEST_SOURCE_OFFSET', 'REQUEST_DESTINATION_OFFSET', 'REQUEST_SOURCE_VAULT_CONTEXT_OFFSET',
  'REQUEST_DESTINATION_VAULT_CONTEXT_OFFSET', 'REQUEST_MINT_OFFSET', 'REQUEST_TOKEN_PROGRAM_OFFSET',
  'REQUEST_PAYER_OFFSET', 'REQUEST_RENT_REFUND_OFFSET', 'REQUEST_EXPECTED_REVISION_OFFSET',
  'REQUEST_RESULTING_REVISION_OFFSET', 'REQUEST_ORDER_NONCE_OFFSET', 'REQUEST_GENERATION_OFFSET',
  'REQUEST_AMOUNT_OFFSET', 'REQUEST_RENT_LAMPORTS_OFFSET', 'REQUEST_PAGE_INDEX_OFFSET',
  'REQUEST_EXECUTION_INDEX_OFFSET', 'REQUEST_RESERVED_OFFSET',
]) output += `export const CUSTODY_${name}_V1 = ${scalar('custodyGenerated', name)} as const;\n`;

// ------------------------------------------------ replay account layout
output += '\n';
for (const name of [
  'REPLAY_VERSION_OFFSET', 'REPLAY_STATUS_OFFSET', 'REPLAY_CALLER_ROLE_OFFSET', 'REPLAY_OPEN_VAULT_COUNT_OFFSET',
  'REPLAY_RELEASE_SET_OFFSET', 'REPLAY_MARKET_OFFSET', 'REPLAY_REALM_OFFSET', 'REPLAY_CONTEXT_OFFSET',
  'REPLAY_CALLER_PROGRAM_OFFSET', 'REPLAY_RENT_REFUND_OFFSET', 'REPLAY_NEXT_REVISION_OFFSET',
  'REPLAY_GENERATION_OFFSET',
]) output += `export const CUSTODY_${name}_V1 = ${scalar('custodyGenerated', name)} as const;\n`;

// ------------------------------------------------------ PDA seed material
output += '\n';
output += `export const CUSTODY_REPLAY_PDA_DOMAIN_V1 = new TextEncoder().encode('${byteString('custodyLib', 'CUSTODY_REPLAY_PDA_DOMAIN_V1')}');\n`;
output += `export const CALLER_AUTHORITY_PDA_DOMAIN_V1 = new TextEncoder().encode('${byteString('releaseSet', 'CALLER_AUTHORITY_PDA_DOMAIN_V1')}');\n`;
output += `export const REGISTRY_ACTIVATION_PDA_DOMAIN_V1 = new TextEncoder().encode('${byteString('registryActivation', 'ACTIVATION_PDA_DOMAIN_V1')}');\n`;
for (const variant of ['Core', 'Claims', 'Trading', 'Resolution', 'Custody']) {
  output += `export const EXECUTION_ROLE_${variant.toUpperCase()}_V1 = ${discriminant('releaseSet', 'ExecutionRoleV1', variant)} as const;\n`;
}
for (const variant of ['InitializeReplay', 'OpenVault', 'Transfer', 'CloseVault', 'CloseReplay']) {
  output += `export const CUSTODY_OPERATION_${variant.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()}_V1 = ${discriminant('custodyLib', 'OperationV1', variant)} as const;\n`;
}
for (const variant of ['None', 'External', 'Settlement', 'HoardPrincipal']) {
  output += `export const CUSTODY_COMPARTMENT_${variant.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()}_V1 = ${discriminant('custodyLib', 'CompartmentV1', variant)} as const;\n`;
}

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== output) {
    console.error('Claims Custody replay TypeScript ABI is stale');
    process.exit(1);
  }
} else {
  writeFileSync(fileURLToPath(outputUrl), output);
}
