#!/usr/bin/env python3
"""Checked arithmetic for the Friday-clutch worked example on the microsite.

The site-plan production note (SITE_CONTENT_MAP_2026-08-20.md §9) requires the
illustration's arithmetic to be generated by a small checked script against the
repo's constants so it can never drift from the semantics it illustrates.

Constants mirrored from the tree:
  D = 64            (illustration's payout denominator; kernel-admissible)
  S = 10_000        (PRICE_SCALE; docs/research/DUAL_IS_THE_MEASURE.md notation)
  MAX_OUTCOMES = 16 (crates/clutch-kernel/src/lib.rs:31) -> C(16,2) = 120
  rounding: canonical largest remainder, lowest-index ties (PROJECT.md §6)

Every number printed here appears verbatim on the site. Run:
  python3 docs/site-plan/friday_clutch_check.py
Exit nonzero on any drift.
"""

from fractions import Fraction
from math import comb

D = 64
S = 10_000
KNOTS = [100, 120, 140, 160, 180, 200, 220, 240]
GAP = 20
X_HAT = Fraction(16340, 100)  # $163.40


def hat_weights_exact(x):
    """Degree-1 open-clamped hats on a uniform grid: exact rational weights*D."""
    ws = []
    for i, t in enumerate(KNOTS):
        left = KNOTS[i - 1] if i > 0 else t
        right = KNOTS[i + 1] if i + 1 < len(KNOTS) else t
        if left <= x <= t and t != left:
            v = Fraction(x - left, t - left)
        elif t <= x <= right and right != t:
            v = Fraction(right - x, right - t)
        elif x == t:
            v = Fraction(1)
        else:
            v = Fraction(0)
        # handle interior points not adjacent to knot i
        if not (left <= x <= right):
            v = Fraction(0)
        ws.append(v * D)
    assert sum(ws) == D, "partition of unity (times D) must hold exactly"
    return ws


def largest_remainder(exact):
    """Canonical largest-remainder quantization with lowest-index ties."""
    floors = [int(e) for e in exact]  # Fraction floor for nonnegative values
    rem = [e - f for e, f in zip(exact, floors)]
    need = D - sum(floors)
    assert 0 <= need <= len(exact)
    order = sorted(range(len(exact)), key=lambda i: (-rem[i], i))
    out = floors[:]
    for i in order[:need]:
        out[i] += 1
    assert sum(out) == D
    return out


failures = []


def check(name, got, want):
    ok = got == want
    print(f"{'ok ' if ok else 'FAIL'} {name}: {got}" + ("" if ok else f" (wanted {want})"))
    if not ok:
        failures.append(name)


# --- resolution weights at $163.40 ---
exact = hat_weights_exact(X_HAT)
check("exact weight*D at knot 160", exact[3], Fraction(D) * Fraction(180 * 100 - 16340, 2000))
w = largest_remainder(exact)
check("quantized weight vector", w, [0, 0, 0, 53, 11, 0, 0, 0])
check("weights sum to D", sum(w), D)

# --- Maya's tent ---
tent = [0, 0, 1, 2, 1, 0, 0, 0]
payout_per_lot = Fraction(sum(c * wi for c, wi in zip(tent, w)), D)
check("tent payout per lot (quantized)", payout_per_lot, Fraction(117, 64))
interp = 2 - Fraction(16340 - 16000, 2000)  # interpolant of c at x-hat
check("tent interpolant at x-hat", interp, Fraction(183, 100))
check("quantization gap below 1/D", abs(interp - payout_per_lot) < Fraction(1, D), True)
check("tent sup-norm (collateral per lot)", max(tent), 2)
check("tent range R(a) per lot", max(tent) - min(tent), 2)

# --- the cleared price vector (illustration) ---
p = [100, 400, 1500, 3300, 2700, 1300, 500, 200]
check("price vector sums to PRICE_SCALE", sum(p), S)
tent_price_num = sum(c * pi for c, pi in zip(tent, p))
check("tent price numerator dot(c,p)", tent_price_num, 10_800)
LOTS = 1600
consideration = Fraction(LOTS * tent_price_num, S)
check("consideration for 1,600 lots is integral", consideration, 1728)

# --- density and forward reads (DUAL_IS_THE_MEASURE §7.3) ---
density = [Fraction(pi, S * GAP) for pi in p]
check("density at $160 (p_i/(S*g))", density[3], Fraction(33, 2000))  # 0.0165/$
check("density integrates to one", sum(d * GAP for d in density), 1)
forward = Fraction(sum(t * pi for t, pi in zip(KNOTS, p)), S)
check("implied forward = one portfolio quote", forward, 170)

# --- ledger walk: H = L + P + S at every frame ---
maya_endow, theo_endow = 2000, 3200
H = maya_endow + theo_endow
L, Pm, Pt, Surp = 0, maya_endow, theo_endow, 0
check("frame endow: H = L+P+S", H, L + Pm + Pt + Surp)
# Theo splits 3,200 complete sets
L, Pt = 3200, 0
check("frame split: H = L+P+S", H, L + Pm + Pt + Surp)
# trade: Maya buys 1,600 tent lots for 1,728 atoms
Pm -= 1728
Pt += 1728
check("frame trade: H = L+P+S", H, L + Pm + Pt + Surp)
check("Maya cash after trade", Pm, 272)
# resolution changes no balances; redemption:
maya_pos = [0, 0, LOTS, 2 * LOTS, LOTS, 0, 0, 0]
theo_pos = [3200, 3200, 3200 - LOTS, 0, 3200 - LOTS, 3200, 3200, 3200]
for i in range(8):
    check(f"claim supply outcome {i} is diagonal", maya_pos[i] + theo_pos[i], 3200)
maya_payout = sum(Fraction(q * wi, D) for q, wi in zip(maya_pos, w))
theo_payout = sum(Fraction(q * wi, D) for q, wi in zip(theo_pos, w))
check("Maya redemption exact (no RemainderRequired)", maya_payout.denominator, 1)
check("Maya payout", maya_payout, 2925)
check("Theo payout", theo_payout, 275)
check("payouts exhaust locked backing", maya_payout + theo_payout, L)
Pm += int(maya_payout)
Pt += int(theo_payout)
L = 0
check("frame redeem: H = L+P+S", H, L + Pm + Pt + Surp)
check("Maya terminal cash", Pm, 3197)
check("Theo terminal cash", Pt, 2003)
# withdraw everything
check("withdrawals drain the Hoard to zero", H - Pm - Pt, 0)
check("Maya P&L", Pm - maya_endow, 1197)
check("zero-sum vs Theo", (Pm - maya_endow) + (Pt - theo_endow), 0)

# --- fee geometry illustration (docs/FEE_GEOMETRY.md §2; fee is forced to 0) ---
G_num = sum(
    p[i] * p[j] * abs(tent[i] - tent[j])
    for i in range(8)
    for j in range(i + 1, 8)
)
check("dispersion numerator G_num(tent,p)", G_num, 40_860_000)
G = Fraction(G_num, S * S)
check("G(tent,p) per lot", G, Fraction(4086, 10_000))
check("Prop 10 envelope G <= R/4", G <= Fraction(max(tent) - min(tent), 4), True)
check("pair terms at MAX_OUTCOMES=16", comb(16, 2), 120)

# --- committed-walk conservation (docs/implementation/COMMITTED_SBF_WALK.md) ---
check("22-step walk closes 70 atoms", 3 + 61 + 6, 70)

# --- compute reattribution ratio (COMPUTE_CEILING_REATTRIBUTION_2026-08-19) ---
check("V2 selection now under ceiling", 226_071 < 1_400_000, True)

if failures:
    raise SystemExit(f"{len(failures)} check(s) failed: {failures}")
print("\nall checks pass — the Friday clutch arithmetic is exact")
