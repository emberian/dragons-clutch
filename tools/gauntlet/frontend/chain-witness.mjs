#!/usr/bin/env node
// Independent finalized-chain decode of one successor campaign's Open Market.
//
// WHY THIS EXISTS. `apps/dclutch-web` renders economics decoded by its own
// `lib/` modules. Screenshotting that and reading it is not evidence: it checks
// the decoder against itself. This module decodes the SAME finalized accounts a
// SECOND time, from byte offsets transcribed directly out of the first-party
// Rust, and speaks raw JSON-RPC rather than going through `lib/rpc.ts`. Nothing
// here imports anything from `apps/dclutch-web`.
//
// Offsets are cited to their semantic owner so a layout change breaks the
// citation, not just the number.
//
//   Core Market state   crates/dclutch-market-core-codec/src/generated.rs
//                       (`// @generated by formal/dclutch-semantics/EmitMarketCoreRust.lean`)
//                       STATE_MAGIC = DCLTCOR2, VERSION = 2, STATE_BYTES = 352,
//                       phase@10 readiness@11 terminal_winner@12 market_id@16
//                       realm@48 product_record@80 product_id@112
//                       resolution_policy@144 capability_manifest@176
//                       selected_release_set@208 registry_program@240
//                       generation@272 outstanding_capabilities@280
//                       rent_beneficiary@288 terminal_receipt@320
//                       Phase { Founding=0 Open=1 Terminal=2 Retiring=3 Retired=4 }
//                       Readiness { Prepaid=0 Ready=1 Consumed=2 }
//   Claims LBv2 state   crates/dclutch-claims-svm/src/liability_basis_state_v2.rs
//                       aggregate DCLLBM02, 256 + 8*claim_count bytes:
//                       claim_count u32@12 revision u64@16 logical_market@24
//                       release_set@56 registry@88 product@120 basis@152
//                       realm@184 custody_context@216 generation u64@248
//                       supplies@256 + i*8
//                       Position DCLLBP02, 128 + 8*claim_count bytes:
//                       claim_count u32@12 revision u64@16 aggregate@24
//                       owner@56 basis@88 balances@128 + i*8
//   Realm               crates/dclutch-realm-contract/src/lib.rs
//                       DCLTRLM1, 112 bytes, mint policy@10 freeze policy@11
//                       token_program@16 collateral_mint@48 adapter_release@80
//   Manifest            crates/dclutch-capability-contract/src/lib.rs
//                       DCLTCAP1, header 16, entry 528: kind@0 program_set@32
//                       config@64 activation_policy@192 dependency_count@193
//                       activation_deadline@200 dependencies@208 quote@224
//   Token-2022 account  mint@0 owner@32 amount u64@64
//
// The required-backing figure is a DERIVATION, not a stored field: the largest
// outcome supply while unresolved, the winning outcome's supply once terminal.
// It is re-derived here from the same supply vector so a disagreement with the
// browser is a disagreement about arithmetic, not about bytes.

import { createHash } from 'node:crypto';

const BASE58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';

export function base58Encode(bytes) {
  let zeros = 0;
  while (zeros < bytes.length && bytes[zeros] === 0) zeros += 1;
  const digits = [];
  for (let index = zeros; index < bytes.length; index += 1) {
    let carry = bytes[index];
    for (let position = 0; position < digits.length; position += 1) {
      carry += digits[position] << 8;
      digits[position] = carry % 58;
      carry = (carry / 58) | 0;
    }
    while (carry > 0) {
      digits.push(carry % 58);
      carry = (carry / 58) | 0;
    }
  }
  return '1'.repeat(zeros) + digits.reverse().map((digit) => BASE58[digit]).join('');
}

export const hex = (bytes) => Buffer.from(bytes).toString('hex');
export const sha256 = (bytes) => new Uint8Array(createHash('sha256').update(Buffer.from(bytes)).digest());

const view = (bytes) => Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength);
const ascii = (bytes, offset, length) => Buffer.from(bytes.slice(offset, offset + length)).toString('latin1');
const u16 = (bytes, offset) => view(bytes).readUInt16LE(offset);
const u32 = (bytes, offset) => view(bytes).readUInt32LE(offset);
const u64 = (bytes, offset) => view(bytes).readBigUInt64LE(offset);
const key = (bytes, offset) => base58Encode(bytes.slice(offset, offset + 32));
const id32 = (bytes, offset) => hex(bytes.slice(offset, offset + 32));

export { ascii, u16, u32, u64, key, id32 };

export class Rpc {
  #id = 0;

  constructor(endpoint) {
    this.endpoint = endpoint;
  }

  async call(method, params) {
    const response = await fetch(this.endpoint, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ jsonrpc: '2.0', id: (this.#id += 1), method, params }),
    });
    if (!response.ok) throw new Error(`${method}: HTTP ${response.status}`);
    const payload = await response.json();
    if (payload.error) throw new Error(`${method} refused: ${JSON.stringify(payload.error)}`);
    return payload.result;
  }

  async finalizedSlot() {
    return String(await this.call('getSlot', [{ commitment: 'finalized' }]));
  }

  async account(address, minContextSlot) {
    const configuration = { commitment: 'finalized', encoding: 'base64' };
    if (minContextSlot !== undefined) configuration.minContextSlot = Number(minContextSlot);
    const raw = await this.call('getAccountInfo', [address, configuration]);
    if (raw.value === null) return null;
    return {
      address,
      owner: raw.value.owner,
      executable: raw.value.executable,
      lamports: String(raw.value.lamports),
      data: new Uint8Array(Buffer.from(raw.value.data[0], 'base64')),
      slot: String(raw.context.slot),
    };
  }

  async programAccounts(programId) {
    const raw = await this.call('getProgramAccounts', [programId, {
      commitment: 'finalized', encoding: 'base64', withContext: true,
    }]);
    return {
      slot: String(raw.context.slot),
      accounts: raw.value.map((entry) => ({
        address: entry.pubkey,
        owner: entry.account.owner,
        executable: entry.account.executable,
        lamports: String(entry.account.lamports),
        data: new Uint8Array(Buffer.from(entry.account.data[0], 'base64')),
      })),
    };
  }
}

export const CORE_PHASES = ['Founding', 'Open', 'Terminal', 'Retiring', 'Retired'];
export const CORE_READINESS = ['Prepaid', 'Ready', 'Consumed'];

export function magicOf(data) {
  return data.length < 8 ? null : ascii(data, 0, 8);
}

/** Decode one live `DCLTCOR2` Core Market state account. */
export function decodeCoreMarketV2(account) {
  const bytes = account.data;
  if (magicOf(bytes) !== 'DCLTCOR2') throw new Error(`Market magic is ${magicOf(bytes)}, not DCLTCOR2`);
  if (bytes.length !== 352) throw new Error(`Core state is ${bytes.length} bytes, layout demands 352`);
  if (u16(bytes, 8) !== 2) throw new Error(`Core state version ${u16(bytes, 8)} is not 2`);
  const phase = CORE_PHASES[bytes[10]];
  const readiness = CORE_READINESS[bytes[11]];
  if (phase === undefined) throw new Error(`phase tag ${bytes[10]} is undefined`);
  if (readiness === undefined) throw new Error(`readiness tag ${bytes[11]} is undefined`);
  const terminalReceipt = id32(bytes, 320);
  const isTerminal = !/^0{64}$/.test(terminalReceipt);
  return {
    address: account.address,
    owner: account.owner,
    accountBytes: bytes.length,
    version: u16(bytes, 8),
    phase,
    readiness,
    terminalWinner: isTerminal ? bytes[12] : null,
    marketId: key(bytes, 16),
    realmId: id32(bytes, 48),
    productRecordId: id32(bytes, 80),
    productInstanceId: id32(bytes, 112),
    resolutionPolicyId: id32(bytes, 144),
    capabilityManifestId: id32(bytes, 176),
    selectedReleaseSetId: id32(bytes, 208),
    registryProgram: key(bytes, 240),
    generation: u64(bytes, 272).toString(),
    outstandingCapabilities: u64(bytes, 280).toString(),
    rentBeneficiary: key(bytes, 288),
    terminalReceiptId: terminalReceipt,
    settled: isTerminal,
    observedSlot: account.slot ?? null,
  };
}

/** Decode one `DCLLBM02` Claims LiabilityBasisV2 aggregate. */
export function decodeClaimsAggregateV2(account) {
  const bytes = account.data;
  if (magicOf(bytes) !== 'DCLLBM02') throw new Error(`aggregate magic is ${magicOf(bytes)}, not DCLLBM02`);
  if (u16(bytes, 8) !== 2) throw new Error(`aggregate version ${u16(bytes, 8)} is not 2`);
  const claimCount = u32(bytes, 12);
  if (bytes.length !== 256 + claimCount * 8) throw new Error(`aggregate is ${bytes.length} bytes for ${claimCount} claims`);
  const supplies = Array.from({ length: claimCount }, (_, index) => u64(bytes, 256 + index * 8));
  return {
    address: account.address,
    owner: account.owner,
    claimCount,
    revision: u64(bytes, 16).toString(),
    logicalMarket: key(bytes, 24),
    releaseSetId: id32(bytes, 56),
    registryProgram: key(bytes, 88),
    productInstanceId: id32(bytes, 120),
    liabilityBasisId: id32(bytes, 152),
    realmId: id32(bytes, 184),
    custodyContext: id32(bytes, 216),
    generation: u64(bytes, 248).toString(),
    supplyAtoms: supplies.map((amount) => amount.toString()),
    maximumSupplyAtoms: supplies.reduce((maximum, amount) => (amount > maximum ? amount : maximum), 0n).toString(),
  };
}

/** Decode one `DCLLBP02` Claims LiabilityBasisV2 Position. */
export function decodeClaimsPositionV2(account) {
  const bytes = account.data;
  if (magicOf(bytes) !== 'DCLLBP02') throw new Error(`Position magic is ${magicOf(bytes)}, not DCLLBP02`);
  if (u16(bytes, 8) !== 2) throw new Error(`Position version ${u16(bytes, 8)} is not 2`);
  const claimCount = u32(bytes, 12);
  if (bytes.length !== 128 + claimCount * 8) throw new Error(`Position is ${bytes.length} bytes for ${claimCount} claims`);
  const balances = Array.from({ length: claimCount }, (_, index) => u64(bytes, 128 + index * 8));
  return {
    address: account.address,
    owner: account.owner,
    claimCount,
    revision: u64(bytes, 16).toString(),
    aggregate: key(bytes, 24),
    positionOwner: key(bytes, 56),
    liabilityBasisId: id32(bytes, 88),
    balances: balances.map((amount) => amount.toString()),
    completeSetsAtoms: balances.reduce((smallest, amount) => (amount < smallest ? amount : smallest), balances[0] ?? 0n).toString(),
  };
}

/** Decode one `DCLTRLM1` Realm record body. */
export function decodeRealmV1(bytes) {
  if (magicOf(bytes) !== 'DCLTRLM1') throw new Error(`Realm magic is ${magicOf(bytes)}, not DCLTRLM1`);
  if (bytes.length !== 112) throw new Error(`Realm is ${bytes.length} bytes, layout demands 112`);
  const policy = (value) => (value === 0 ? 'Require absent' : value === 1 ? 'Admit issuer control' : null);
  return {
    contentDigest: hex(sha256(bytes)),
    mintAuthorityPolicy: policy(bytes[10]),
    freezeAuthorityPolicy: policy(bytes[11]),
    tokenProgram: key(bytes, 16),
    collateralMint: key(bytes, 48),
    adapterReleaseId: id32(bytes, 80),
  };
}

/** Decode one `DCLTCAP1` capability manifest record body. */
export function decodeCapabilityManifestV1(bytes) {
  if (magicOf(bytes) !== 'DCLTCAP1') throw new Error(`manifest magic is ${magicOf(bytes)}, not DCLTCAP1`);
  if (u16(bytes, 8) !== 1) throw new Error(`manifest version ${u16(bytes, 8)} is not 1`);
  const count = u16(bytes, 12);
  if (bytes.length !== 16 + count * 528) throw new Error(`manifest is ${bytes.length} bytes for ${count} entries`);
  return Array.from({ length: count }, (_, index) => {
    const offset = 16 + index * 528;
    const policy = bytes[offset + 192];
    const dependencyCount = bytes[offset + 193];
    return {
      index,
      kindId: id32(bytes, offset + 0),
      programSetId: id32(bytes, offset + 32),
      configId: id32(bytes, offset + 64),
      activation: policy === 0 ? 'immediate' : 'deadline',
      deadline: policy === 0 ? null : u64(bytes, offset + 200).toString(),
      dependencies: Array.from({ length: dependencyCount }, (_, slot) => bytes[offset + 208 + slot]),
      fundingMagic: ascii(bytes, offset + 224, 8),
    };
  });
}

/** Decode the amount held by one SPL/Token-2022 token account. */
export function decodeTokenAmount(account) {
  if (account.data.length < 72) throw new Error('token account is shorter than the base layout');
  return {
    mint: key(account.data, 0),
    owner: key(account.data, 32),
    amount: u64(account.data, 64).toString(),
  };
}
