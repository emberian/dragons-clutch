#!/bin/sh
set -eu

# Exact-output check for the Lean-emitted Direct transition program.
#
# src/generated_direct_program.rs is the checked-in image of
# formal/dclutch-semantics/EmitDirectProgramRust.lean. This script re-emits it
# and byte-compares, so a Lean edit that is not carried into the include is a
# red gate rather than a silent divergence.

validator_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$validator_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "${TMPDIR:-/tmp}/dclutch-direct-program.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.DirectProgram
  lake env lean EmitDirectProgramRust.lean
  lake env lean --run EmitDirectProgramRust.lean > "$generated"
)

test "$(sed -n '1p' "$generated")" = \
  '// @generated by formal/dclutch-semantics/EmitDirectProgramRust.lean; do not edit.'
grep -q '^pub(crate) const DIRECT_PROGRAM: \[u8; [0-9]*\] = \[$' "$generated"
rustup run 1.97.1 rustfmt --edition 2024 "$generated"
cmp "$generated" "$validator_dir/src/generated_direct_program.rs"
