def atoms(price_units):
    """Exact decimal display of price units as collateral atoms (units/S)."""
    quarter = Fraction(price_units, S)
    if quarter.denominator == 1:
        return str(quarter.numerator)
    return f"{price_units / S:.4f}".rstrip("0")


