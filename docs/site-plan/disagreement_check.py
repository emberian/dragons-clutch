print("--- the measure instance (Theorem 7.1, instantiated by arithmetic) ---")
# Degree-1 hats are cardinal: N_j(t_i) = delta_ij exactly (exact rationals).
def hat_exact(i, x):
    x = min(max(x, KNOTS[0]), KNOTS[-1])
    t = KNOTS[i]
    if i > 0 and KNOTS[i - 1] <= x <= t:
        return Fraction(x - KNOTS[i - 1], GAP)
    if i + 1 < N and t <= x <= KNOTS[i + 1]:
        return Fraction(KNOTS[i + 1] - x, GAP)
    return Fraction(1) if x == t else Fraction(0)

