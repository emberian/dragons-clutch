def hat(i, x):
    """Degree-1 clamped hat i at x: EDGE-CLAMP-01 clamps x to [t_0, t_{n-1}]."""
    x = min(max(x, KNOTS[0]), KNOTS[-1])
    t = KNOTS[i]
    if i > 0 and KNOTS[i - 1] <= x <= t:
        return (x - KNOTS[i - 1]) / GAP
    if i + 1 < N and t <= x <= KNOTS[i + 1]:
        return (KNOTS[i + 1] - x) / GAP
    if x == t:
        return 1.0
    return 0.0


def norm_cdf(z):
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def gaussian_hat_moments(m, s):
    """E[N_i(clamp(X))], X lognormal(m, s^2): exact piecewise partial moments."""
    def prob(a, b):
        return norm_cdf((math.log(b) - m) / s) - norm_cdf((math.log(a) - m) / s)

    def partial_mean(a, b):  # E[X ; a < X < b]
        shift = math.exp(m + s * s / 2.0)
        return shift * (
            norm_cdf((math.log(b) - m - s * s) / s)
            - norm_cdf((math.log(a) - m - s * s) / s)
        )

    out = []
    for i, t in enumerate(KNOTS):
        weight = 0.0
        if i == 0:
            weight += norm_cdf((math.log(KNOTS[0]) - m) / s)  # clamp below
        else:
            a = KNOTS[i - 1]
            weight += (partial_mean(a, t) - a * prob(a, t)) / GAP
        if i == N - 1:
            weight += 1.0 - norm_cdf((math.log(KNOTS[-1]) - m) / s)  # clamp above
        else:
            b = KNOTS[i + 1]
            weight += (b * prob(t, b) - partial_mean(t, b)) / GAP
        out.append(weight)
    return out


def largest_remainder(weights, total):
    """Canonical largest-remainder quantization, lowest-index ties."""
    exact = [w * total for w in weights]
    floors = [math.floor(e) for e in exact]
    need = total - sum(floors)
    order = sorted(range(len(exact)), key=lambda i: (floors[i] - exact[i], i))
    out = floors[:]
    for i in order[:need]:
        out[i] += 1
    assert sum(out) == total
    return out


