print("--- self-assessed edges: both sides think they won ---")
# Each side re-values its own trades under its own belief vector (price
# units, exact).  G's light: value bought minus paid, received minus value
# sold.  The cleared price cancels in the sum, leaving the traded quantity
# against the belief gap: the disagreement traded IS the total perceived gain.
def edge(owner, beliefs):
    total = 0
    for i in TRADED:
        buyer, buy_limit, seller, sell_limit = singles[i]
        if buyer == owner:
            total += Z * (beliefs[i] - P[i])
        if seller == owner:
            total += Z * (P[i] - beliefs[i])
    if owner == "G":
        total += LOTS * (sum(c * v for c, v in zip(C_PLUS, beliefs)) - dot_p)
    else:
        total += LOTS * (dot_p - sum(c * v for c, v in zip(C_PLUS, beliefs)))
    return total

