print("--- SYN-1 regeneration (seed 20260827; float boundary: libm) ---")
rng = random.Random(SEED)
returns = []
jump_days = 0
for _ in range(NDAYS):
    step = rng.gauss(0, DAILY_SIGMA)
    if rng.random() < JUMP_PROBABILITY:
        step += rng.choice([-JUMP, JUMP])
        jump_days += 1
    returns.append(step)
