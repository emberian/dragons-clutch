#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/.generated-capability-execution.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.CapabilityExecutionAbi
  lake env lean --run EmitCapabilityExecutionAbiRust.lean > "$generated"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitCapabilityExecutionAbiRust.lean; do not edit.'
grep -q '^pub const CAPABILITY_EXECUTION_SELECTION_BYTES_V1: usize = 144;$' "$generated"
rustfmt --edition 2024 "$generated"
cmp "$generated" "$crate_dir/src/generated_capability_execution.rs"
