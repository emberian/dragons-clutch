const RESERVED_RECEIPT_BYTES: usize = 16;

/// Stable refusal returned by the canonical Custody contract.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Error {
    /// A wire did not have its one exact width.
    InvalidLength,
    /// Magic bytes selected another wire family.
    InvalidMagic,
    /// A wire named an unsupported schema.
    UnsupportedSchema,
    /// An operation discriminator was unknown.
    UnknownOperation,
    /// A caller execution role was unknown or selected Custody itself.
    UnknownCallerRole,
    /// A collateral-compartment tag was unknown.
    UnknownCompartment,
    /// Reserved or operation-inactive bytes were nonzero.
    NonCanonicalBytes,
    /// A required identity or digest was all zero.
    ZeroIdentity,
    /// Exact source and destination accounts aliased.
    AliasedTransferAccounts,
    /// An external token side lacked one exact nonzero semantic owner.
    ExternalActorRequired,
    /// Optimistic replay arithmetic overflowed or skipped a revision.
    RevisionOverflow,
    /// Request fields did not form the selected operation's exact shape.
    InvalidOperationShape,
    /// Persisted replay authority differed from the current request.
    ReplayBindingMismatch,
    /// The expected revision had already been consumed or was stale.
    ReplayRevisionMismatch,
    /// Exact transfer balance arithmetic overflowed or underflowed.
    BalanceArithmetic,
    /// A receipt did not acknowledge the exact request and poststate.
    ReceiptMismatch,
}

/// Result alias for Custody contract operations.
pub type Result<T> = core::result::Result<T, Error>;

/// Physical operation executed by Custody.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum OperationV1 {
    /// Create and bind one replay cursor from prepaid rent.
    InitializeReplay = 0,
    /// Create an empty Realm-selected token vault.
    OpenVault = 1,
    /// Move one positive exact collateral quantity.
    Transfer = 2,
    /// Close one empty Realm-selected token vault to its named rent refund.
    CloseVault = 3,
}

impl OperationV1 {
    fn decode(value: u8) -> Result<Self> {
        match value {
            0 => Ok(Self::InitializeReplay),
            1 => Ok(Self::OpenVault),
            2 => Ok(Self::Transfer),
            3 => Ok(Self::CloseVault),
            _ => Err(Error::UnknownOperation),
        }
    }
}

/// Economic compartment labeling one exact token account role.
///
/// These tags are evidence, not balances. The caller remains the sole owner of
/// its economic transition. Their distinct encodings prevent a receipt for
/// Hoard principal from being accepted as a fee, liveness, recovery, or rent
/// effect. Rent has no token-compartment tag at all.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum CompartmentV1 {
    /// Canonical inactive value for a non-transfer side.
    None = 0,
    /// Externally owned depositor, recipient, executor, or beneficiary.
    External = 1,
    /// General settlement inventory.
    Settlement = 2,
    /// Market Hoard principal, never fee or liveness capital.
    HoardPrincipal = 3,
    /// Direct or Dealer trading principal.
    TradingPrincipal = 4,
    /// Physically segregated realized fees.
    FeeVault = 5,
    /// Present funded-liveness capital.
    LivenessVault = 6,
    /// Series Ticket principal before Market creation.
    SeriesEscrow = 7,
    /// Present recovery-reserve capital.
    RecoveryReserve = 8,
}

impl CompartmentV1 {
    fn decode(value: u8) -> Result<Self> {
        match value {
            0 => Ok(Self::None),
            1 => Ok(Self::External),
            2 => Ok(Self::Settlement),
            3 => Ok(Self::HoardPrincipal),
            4 => Ok(Self::TradingPrincipal),
            5 => Ok(Self::FeeVault),
            6 => Ok(Self::LivenessVault),
            7 => Ok(Self::SeriesEscrow),
            8 => Ok(Self::RecoveryReserve),
            _ => Err(Error::UnknownCompartment),
        }
    }

    /// Return the canonical one-byte physical compartment seed.
    pub const fn tag(self) -> u8 {
        self as u8
    }
}

