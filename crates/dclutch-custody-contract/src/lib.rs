//! Generated fixed-layout semantic contract for canonical collateral custody.
//!
//! The contract is SDK-free, allocation-free, and total over hostile bytes.
//! It owns one transfer projection and one replay cursor shared by every
//! execution role. The composing adapter remains responsible for hashing,
//! Registry CPI and return-data provenance, PDA derivation, exact Realm and
//! token-state parsing, token/System CPI, account ownership, and transaction
//! rollback.

