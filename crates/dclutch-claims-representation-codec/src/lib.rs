/// Exact canonical representation action wire width.
pub const ACTION_WIRE_BYTES_V1: usize = ACTION_BYTES;

/// Economic lifecycle projected by the EconomicKernel owner.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EconomicPhase {
    /// Market liabilities may be issued, represented, or redeemed.
    Open,
    /// A winner exists and terminal claims may be redeemed.
    Terminal,
    /// Terminal redemption is underway.
    Retiring,
    /// Market-level economics are fully retired.
    Retired,
}

impl EconomicPhase {
    const fn mask(self) -> u8 {
        match self {
            Self::Open => PHASE_OPEN,
            Self::Terminal => PHASE_TERMINAL,
            Self::Retiring => PHASE_RETIRING,
            Self::Retired => PHASE_RETIRED,
        }
    }
}

