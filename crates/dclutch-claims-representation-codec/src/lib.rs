#![forbid(unsafe_code)]
#![deny(missing_docs)]

//! Allocation-free interpreter for Lean-owned claim-representation data.
//!
//! The interpreter prepares one exact wrapper successor, one adapter intent,
//! and a borrowed iterator of EconomicKernel intents. It does not mutate or
//! duplicate Market supply, Hoard, native/materialized supply, token state, or
//! Registry authority. A physical adapter must apply every prepared component
//! atomically before persisting [`PreparedTransition::post_state`].

/// Stable refusal from hostile decoding or transition admission.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Error {
    /// A fixed or descriptor-derived wire width was not exact.
    InvalidLength,
    /// The requested wire type's magic bytes differed.
    InvalidMagic,
    /// The ABI version is unsupported.
    UnsupportedVersion,
    /// Reserved bytes or a boolean byte were noncanonical.
    NonCanonicalReserved,
    /// A required identity was all zero.
    ZeroIdentity,
    /// The descriptor had no outcomes or no positive claim weight.
    InvalidClaimVector,
    /// A receipt-lot scale was zero.
    ZeroReceiptUnits,
    /// The action tag was not generated by Lean.
    UnknownAction,
    /// The selected release set or normalized receipt was substituted.
    ReleaseMismatch,
    /// Registry/Claims release authentication was incomplete.
    UnauthenticatedRelease,
    /// Descriptor, state, or action identities did not join exactly.
    IdentityMismatch,
    /// Optimistic replay nonce or issued-lot coordinates were stale.
    ReplayMismatch,
    /// The wrapper capability was already retired.
    AlreadyRetired,
    /// The Economic-owner phase does not admit the generated action rule.
    InvalidPhase,
    /// A required lot count was zero or retirement carried nonzero lots.
    InvalidLots,
    /// A redemption exceeded issued lots or retirement was nonempty.
    InsufficientLots,
    /// Nonce advancement overflowed `u64`.
    NonceOverflow,
    /// Lot, claim, or receipt arithmetic overflowed `u64`.
    ArithmeticOverflow,
}

/// Result alias for this interpreter.
pub type Result<T> = core::result::Result<T, Error>;

/// Generated wrapper-state lot mutation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LotEffect {
    /// Add issued lots.
    Add,
    /// Subtract redeemed lots.
    Subtract,
    /// Require zero lots and retire the wrapper child.
    Retire,
}

/// Generated EconomicKernel intent style.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EconomicStyle {
    /// Convert claimant-native claims into wrapper materialized claims.
    Materialize,
    /// Convert wrapper materialized claims back to claimant-native claims.
    Dematerialize,
    /// Dematerialize, then terminally redeem every nonzero basket claim.
    Terminal,
    /// Emit no Market-level economic transition.
    None,
}

/// Generated representation-adapter intent style.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AdapterStyle {
    /// Mint exact receipt units to the authenticated claimant.
    Mint,
    /// Burn exact receipt units from the authenticated claimant.
    Burn,
    /// Retire an empty representation adapter child.
    Retire,
}

/// One immutable Lean-generated action rule.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ActionRule {
    tag: u8,
    allowed_phases: u8,
    lot_effect: LotEffect,
    requires_positive_lots: bool,
    economic_style: EconomicStyle,
    adapter_style: AdapterStyle,
}

