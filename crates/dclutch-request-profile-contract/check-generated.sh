#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/.generated-request-profile.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.RequestProfileAbi
  lake env lean --run EmitRequestProfileAbiRust.lean > "$generated"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitRequestProfileAbiRust.lean; do not edit.'
grep -q '^pub const REQUEST_PROFILE_HEADER_BYTES_V1: usize = 32;$' "$generated"
grep -q '^pub const REQUEST_PROFILE_OPERATION_BYTES_V1: usize = 24;$' "$generated"
grep -q '^pub const REQUEST_PROFILE_MAX_BYTES_V1: usize = 1312;$' "$generated"
grep -Fq 'pub const REQUEST_PROFILE_SCHEMA_RELEASE_PREIMAGE_V1: &[u8] = &[' "$generated"
grep -Fq 'pub const REQUEST_PROFILE_SCHEMA_RELEASE_ID_V1: [u8; 32] = [' "$generated"
grep -q '^pub const AGREEMENT_PROFILE_V1: \[u8; 152\]' "$generated"
grep -q '^pub const AGREEMENT_REQUEST_TAIL2_V1: \[u8; 96\]' "$generated"
grep -q '^pub const PROFILE_REFUSAL_CORPUS_V1: \[\[u8; 152\]; 10\]' "$generated"
grep -q '^pub const REQUEST_REFUSAL_CORPUS_TAIL2_V1: \[\[u8; 96\]; 2\]' "$generated"
grep -q '^pub const OVERSIZED_PROFILE_V1: \[u8; 1328\]' "$generated"
rustfmt --edition 2024 "$generated"

schema_digest=$(sed -n '/^pub const REQUEST_PROFILE_SCHEMA_RELEASE_PREIMAGE_V1:/,/^];/p' "$generated" |
  grep -o '0x[0-9a-f][0-9a-f]' | sed 's/0x//' | tr -d '\n' | xxd -r -p | shasum -a 256 |
  awk '{print $1}')
schema_id=$(sed -n '/^pub const REQUEST_PROFILE_SCHEMA_RELEASE_ID_V1:/,/^];/p' "$generated" |
  grep -o '0x[0-9a-f][0-9a-f]' | sed 's/0x//' | tr -d '\n')
test "$schema_digest" = "$schema_id"

cmp "$generated" "$crate_dir/src/generated.rs"
