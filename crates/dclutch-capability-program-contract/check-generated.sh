#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repository_dir/formal/dclutch-semantics"
generated=$(mktemp "$crate_dir/src/.generated-capability-program.XXXXXX")
trap 'rm -f "$generated"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.CapabilityProgramAbi
  lake env lean --run EmitCapabilityProgramAbiRust.lean > "$generated"
)

first_line=$(sed -n '1p' "$generated")
test "$first_line" = '// @generated by formal/dclutch-semantics/EmitCapabilityProgramAbiRust.lean; do not edit.'
grep -q '^pub const CAPABILITY_PROGRAM_MAX_BYTES_V1: usize = 1312;$' "$generated"
grep -q '^pub const CAPABILITY_ROOT_HEADER_BYTES_V1: usize = 232;$' "$generated"
rustfmt --edition 2024 "$generated"
cmp "$generated" "$crate_dir/src/generated.rs"
