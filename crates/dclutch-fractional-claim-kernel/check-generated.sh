#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/generated_abi.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-fractional-claim-v1.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.FractionalClaimV1
  lake env lean --run EmitFractionalClaimV1AbiRust.lean > "$temporary"
)

expected_header='// @generated by formal/dclutch-semantics/EmitFractionalClaimV1AbiRust.lean; do not edit.'
test "$(sed -n '1p' "$temporary")" = "$expected_header"
test "$(wc -l < "$temporary" | tr -d ' ')" -eq 30
cmp "$temporary" "$accepted"
