#!/bin/sh
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(CDPATH= cd -- "$crate_dir/../.." && pwd)
formal_dir="$repo_dir/formal/dclutch-semantics"
accepted="$crate_dir/src/generated_spline.rs"
temporary=$(mktemp "${TMPDIR:-/tmp}/dclutch-liability-basis-v2-spline.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

(
  cd "$formal_dir"
  lake build DClutchSemantics.LiabilityBasisV2SplineAbi
  lake env lean --run EmitLiabilityBasisV2SplineRust.lean > "$temporary"
)

expected_header='// @generated by formal/dclutch-semantics/EmitLiabilityBasisV2SplineRust.lean; do not edit.'
test "$(sed -n '1p' "$temporary")" = "$expected_header"
test "$(sed -n '2p' "$temporary")" = 'use super::{SplineAgreementCaseV2, SplineRefusalCaseV2};'
test "$(wc -l < "$temporary" | tr -d ' ')" -eq 326
grep -q '^pub const SPLINE_AGREEMENT_CASES_V2: \[SplineAgreementCaseV2; 28\] = \[$' "$temporary"
grep -q '^pub const SPLINE_REFUSAL_CASES_V2: \[SplineRefusalCaseV2; 32\] = \[$' "$temporary"
cmp "$temporary" "$accepted"
